"""
Точечная проверка гипотезы про три новых примера, добавленных в _CORE_RULES
(live_hints.py) в форме "как ты поступишь/что будешь делать, если..."
(см. PROGRESS.md и обсуждение в чате). После добавления примеров
batch_test_situational.py на всех 24 вопросах показал 0 изменений — эта
проверка узкая, чтобы понять ПОЧЕМУ: примеры вообще не "цепляются" (даже
дословный повтор одного из них не подхватывает нужный формат ответа), или
цепляются только дословно, но не переживают даже лёгкий перефраз.

Для каждого примера — два вопроса:
  1. "точно"   — фраза, ОЧЕНЬ близкая к тому, что дословно есть в промпте
                 (базовая проверка: работает ли пример вообще, хоть на
                 своём же содержании).
  2. "перефраз" — та же ситуация, другими словами (то, что нас реально
                 интересует — переживает ли пример лёгкий перефраз).

Примеры 1-3 — на общей нерабочей лексике ("трафик упал", "демо", "сроки").
Первый прогон этого скрипта показал: 5 из 6 сработали правильно — значит
примеры в принципе "цепляются" и обобщаются на перефраз. Но при этом на
всех 24 вопросах из situational_questions.json (сплошь QA-лексика: баг,
автотест, тест-план) результат был 0/24 и до, и после добавления этих
примеров. Рабочая гипотеза: дело не в форме вопроса, а в лексике — QA-слова
("баг", "тестирование") сами по себе утягивают модель в режим "отвечаю
уверенно по своим знаниям" (правило 2), а не "это ситуационный вопрос без
единственного ответа" (правило 3). Примеры 4-5 — на такой же грамматической
форме, но уже с QA-лексикой (тестовый стенд, нагрузочное тестирование) —
проверяем, тянет ли это правило 3 обратно, когда лексика техническая.

KB намеренно выключена (--no-kb эквивалент через kb_enabled=False) — это
не про базу знаний, чтобы не путать с тем экспериментом.

Запуск (из корня проекта):
    venv\\Scripts\\python.exe src\\test_new_examples.py
"""
from __future__ import annotations

import time

from config import Settings
from live_hints import generate_hint

CASES = [
    ("пример 1, точно", "Собеседник: как ты поступишь, если увидишь, что в проде упала половина трафика?"),
    ("пример 1, перефраз", "Собеседник: что будешь делать, если заметишь, что в проде трафик упал наполовину?"),
    ("пример 2, точно", "Собеседник: что будешь делать, если на демо для клиента не заработает ключевая фича?"),
    ("пример 2, перефраз", "Собеседник: как поступишь, если во время демо для клиента отвалится основная функция?"),
    ("пример 3, точно", "Собеседник: как поступишь, если менеджер просит оценить сроки, а требований толком нет?"),
    ("пример 3, перефраз", "Собеседник: что сделаешь, если тебя просят назвать сроки, а требования ещё не готовы?"),
    ("пример 4 (QA-лексика), точно", "Собеседник: что будешь делать, если заказчик просит протестировать фичу, а у тебя нет доступа к тестовому стенду?"),
    ("пример 4 (QA-лексика), перефраз", "Собеседник: как поступишь, если клиент хочет, чтобы ты протестировал фичу, а тестового стенда у тебя нет?"),
    ("пример 5 (QA-лексика), точно", "Собеседник: как поступишь, если во время нагрузочного тестирования сервер упал раньше ожидаемого порога?"),
    ("пример 5 (QA-лексика), перефраз", "Собеседник: что будешь делать, если сервер не выдержал нагрузку и упал раньше, чем ты ожидал во время теста?"),
]


def main() -> None:
    settings = Settings.load()
    print(f"Модель: {settings.ollama_model} ({settings.ollama_host})")
    print("База знаний: выключена (для этой проверки не нужна)\n")

    for label, transcript in CASES:
        t0 = time.time()
        reply, context = generate_hint(
            transcript,
            model=settings.ollama_model,
            host=settings.ollama_host,
            kb_enabled=False,
            kb_path=None,
            kb_top_k=settings.kb_top_k,
            kb_min_score=settings.kb_min_score,
        )
        elapsed = time.time() - t0
        looks_like_clarification = reply.rstrip().endswith("?")
        flag = "ПОХОЖЕ НА УТОЧНЕНИЕ" if looks_like_clarification else "план/совет, не вопрос"

        print(f"[{label}] ({elapsed:.1f}с, {flag})")
        print(f"  Вопрос: {transcript.replace('Собеседник: ', '')}")
        print(f"  Ответ:  {reply}")
        print()


if __name__ == "__main__":
    main()

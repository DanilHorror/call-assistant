# Живой разговор в основном состоит из фраз, которые НЕ являются вопросом
# или просьбой к нам — обычная болтовня, согласия, обсуждение постороннего
# (см. реальный лог: "Ничего себе.", "Так-так-так, щас-щас-щас.", "DOD" и
# т.п.). Раньше КАЖДАЯ такая фраза всё равно уходила в Ollama — и там модель
# либо честно отвечала "ОТВЕТ: -" (см. _parse_hint), либо (что оказалось
# намного чаще на практике) с temperature=0 сразу выдавала стоп-маркер, ещё
# не написав "ОТВЕТ:" — а это для _call_ollama_retrying неотличимо от того
# самого редкого бага с пустой генерацией на холодном старте, под который
# retry и делался, так что код честно пробовал ещё 2 раза, прежде чем сдаться
# с тем же самым результатом "вопроса нет". На реальном звонке (см. лог) это
# давало по 2-3 лишних похода в Ollama практически на каждую реплику болтовни
# — не только лишняя задержка на будущий настоящий вопрос (Ollama всё это
# время занята), но и сама вероятная причина ощущения "то отвечает, то как
# будто зависает/обрывается".
#
# Эвристика ниже — не про смысл фразы (это стоило бы отдельного похода в
# модель, то есть свело бы экономию к нулю), а про формальный признак: без
# "?" и без явного слова-просьбы фраза почти никогда не адресована нам.
# Риск — пропустить реальный вопрос, заданный без "?"; на практике в этом
# домене (рабочие звонки, вопросы по теме) whisper почти всегда пунктуирует
# настоящий вопрос знаком "?" (видно по логам), так что риск невелик.
# Отдельно проверяем "ожидает ли модель уточнения" (pending_clarification) —
# ответ НА НАШ ЖЕ уточняющий вопрос часто не содержит ни "?", ни этих слов
# ("да, про Redis" и т.п.), но всё равно должен дойти до модели.
_REQUEST_VERB_RE = re.compile(
    r"\b(расскаж\w*|объясн\w*|подскаж\w*|скаж\w*|посовету\w*|"
    r"поясни\w*|помоги\w*|покаж\w*|привед\w*|назов\w*|опиш\w*|сравни\w*)\b",
    re.IGNORECASE,
)

# Реальный случай: "Давайте через команду Find найдем файлы, которые старше
# двух дней и удалим их." — это классическая формулировка практического
# задания в разговоре ("давайте сделаем X"), но ни "?", ни один из
# глаголов-просьб выше в ней нет ("найдём"/"удалим" не входят в тот список,
# да и списком все возможные глаголы не перечислить). В итоге реплика вообще
# не считалась вопросом/просьбой и хинт на неё не запускался ни разу — не
# устаревший ответ, а полное отсутствие ответа. "Давай"/"Давайте" в начале
# такой практической реплики в этом домене (рабочие звонки) почти всегда
# означает именно предложение сделать/разобрать что-то конкретное — ловим
# это отдельно, независимо от того, какой глагол идёт дальше.
_LETS_DO_RE = re.compile(r"\bдавай(?:те)?\b", re.IGNORECASE)

# Реальный лог 2026-09-13 показал ещё один источник той же проблемы, что и
# бэкчаннел выше, но не ловящийся им: короткая реплика собеседника "Это что,
# Данил?", прозвучавшая через 9 секунд ПОСЛЕ настоящего вопроса "А что такое
# дефект или баг? Какие основные поля у баг-репорта?" — из-за одного "?" она
# сама была признана "новым вопросом" (см. _QUESTION_OR_REQUEST_RE ниже по
# правкам истории), тут же оборвала ещё считавшийся ответ модели на реальный
# вопрос (тогда это ещё обрывало генерацию — см. историю у hint_request_queue
# в main(), с тех пор очередь стала FIFO и так больше не делает) и заменила
# его собой — а сама содержательного ответа не заслуживала и никакого не
# получила ("реплика без вопроса/просьбы"). В логе видно и другой похожий
# случай — "Хочешь ещё вопрос?" — это тоже реплика О самом разговоре, а не
# вопрос К нам. Фильтр ниже по-прежнему нужен и без обрыва — такая реплика
# всё равно попала бы в очередь отдельным, заведомо бесполезным запросом.
#
# Отличить короткую реакцию/обращение по имени ("Это что, Данил?", 3 слова)
# от короткого, но настоящего содержательного вопроса ("Что такое REST?",
# тоже 3 слова) по одной только длине нельзя. Поэтому для КОРОТКИХ реплик
# требуем ещё и явный вопросительный маркер по содержанию — "что такое",
# "как", "почему", "какие" и т.п., а не просто "?" где-то в тексте. Длинные
# реплики (>= порога слов) по-прежнему считаются вопросом по одному "?" —
# именно так пунктуирует реальные вопросы Whisper в этом домене (см.
# комментарий про _looks_like_question_or_request выше).
_STRONG_QUESTION_MARKER_RE = re.compile(
    r"\b(что\s+такое|как(?:ой|ая|ое|ие|их|им|ими)?\b|почему|зачем|"
    r"где\b|когда\b|сколько|чем\b|в\s+ч[её]м|отлича\w*|разниц\w*)\b",
    re.IGNORECASE,
)
_MIN_WORDS_FOR_BARE_QUESTION_MARK = 5

# Реальный случай: "Как посмотреть таблицу маршрутизации?" и через 4 секунды
# ОТДЕЛЬНОЙ строкой транскрипта — "и чем отличаются протоколы TCP-UDP." Это
# один составной вопрос собеседника, просто VAD/whisper разрезали его на две
# фразы по паузе — а вторая часть при этом ещё и осталась БЕЗ "?" (whisper
# пунктуировал её как обычное продолжение предложения, не как вопрос), хотя
# по содержанию ("чем отличаются") это, конечно, вопрос. Через основную
# проверку "есть '?' — не пропустить" эта строка вообще не проходит, и
# запрос в Ollama на неё никогда не уходит. Ловим отдельно: реплика,
# начинающаяся с союза-продолжения ("и"/"а"/"но"/"или"/"да") и вскоре после
# него содержащая явный вопросительный маркер по содержанию — это, скорее
# всего, вторая половина того же составного вопроса, даже без "?".
_CONTINUATION_QUESTION_RE = re.compile(
    r"^\s*(?:и|а|но|или|да)\b.{0,24}?\b(что\s+такое|как(?:ой|ая|ое|ие|их|им|ими)?\b|"
    r"почему|зачем|где\b|когда\b|сколько|чем\b|в\s+ч[её]м|отлича\w*|разниц\w*)\b",
    re.IGNORECASE,
)


def _looks_like_question_or_request(text: str) -> bool:
    if _REQUEST_VERB_RE.search(text):
        return True
    if _LETS_DO_RE.search(text):
        return True
    if _CONTINUATION_QUESTION_RE.match(text):
        return True
    if "?" not in text:
        return False
    if _STRONG_QUESTION_MARKER_RE.search(text):
        return True
    word_count = len(re.findall(r"\w+", text, re.UNICODE))
    return word_count >= _MIN_WORDS_FOR_BARE_QUESTION_MARK


# --- Этап 3: "сложные" вопросы (алгоритмические задачи по программированию,
# ситуационные вопросы вида "как поступишь, если...") — локальная модель на
# 8ГБ видеокарте на них заметно слабее, чем на обычных фактических вопросах
# (см. историю в README/переписке).
#
# Изначально эта классификация решала "GigaChat или Ollama". По итогам
# массовых сравнительных прогонов (src/batch_test*.py --backend gigachat на
# реальных вопросах) выяснилось, что GigaChat не хуже (и быстрее) локальной
# Ollama и на ОБЫЧНЫХ вопросах тоже — так что теперь, если GigaChat вообще
# настроена (GIGACHAT_ENABLED=true в .env), она отвечает на ВСЕ вопросы, а
# is_hard решает только, КАКУЮ модель GigaChat взять: settings.gigachat_model
# (сильная/дорогая, например Ultra) для сложных, settings.gigachat_normal_model
# (лёгкая/дешёвая, например Lite) — для всех остальных. Ollama осталась
# ЕДИНСТВЕННЫМ запасным вариантом — но не по этой классификации (see
# hint_worker ниже): переключение на неё чисто механическое, по факту сбоя
# запроса к GigaChat (сеть, лимит токенов, ключ), а не по "сложности"
# вопроса — само понятие "сложный вопрос" слишком нечёткое, чтобы на нём
# строить выбор между облаком и локалью, это обсуждали отдельно.
#
# Это ДОПОЛНИТЕЛЬНАЯ проверка поверх _looks_like_question_or_request() —
# вызывается только для того, что и так уже прошло тот фильтр, здесь не
# нужно заново отсекать "не вопрос вообще".
_ALGO_TASK_RE = re.compile(
    r"\b(алгоритм\w*|напиши\w*\s+(?:функци\w*|код|запрос|скрипт|программ\w*)|"
    r"написать\s+(?:функци\w*|код|запрос)|реализуй\w*|реализовать|"
    r"структур\w*\s+данных|отсортиру\w*|сортировк\w*|рекурси\w*|"
    r"бинарн\w*\s+поиск|связ\w*\s+список|хеш-?таблиц\w*|sql[-\s]?запрос|"
    r"паттерн\w*\s+проектирования|дедлок|race\s+condition|leetcode|литкод)\b",
    re.IGNORECASE,
)

# "как поступишь, если..." / "что будешь делать, если..." — форма вопроса
# про КОНКРЕТНУЮ ситуацию (см. пункт 3 в _CORE_RULES, live_hints.py): модели
# тут нужно и понять, хватает ли деталей, и, если хватает, построить связное
# решение, а не просто вспомнить факт — GigaChat заметно надёжнее локальной
# 7B-модели именно в такого рода рассуждении.
_SITUATIONAL_HARD_RE = re.compile(
    r"\b(как\s+(?:ты\s+)?поступ\w*|что\s+(?:ты\s+)?буд(?:ешь|ете)\s+делать)\b[^.?!]{0,60}\bесли\b",
    re.IGNORECASE,
)

# "давай(те) сделаем X" (см. _LETS_DO_RE выше) сам по себе слишком общий —
# ловит и обычное "давай в 15:00, мне подходит", для которого GigaChat не
# нужна. Тут — только "давай(те)" РЯДОМ с явным техническим действием
# (команда, скрипт, запрос и т.п.), как в реальном случае из истории:
# "давайте через команду find найдём файлы старше двух дней и удалим их".
_LETS_DO_HARD_RE = re.compile(
    r"\bдавай(?:те)?\b.{0,40}\b(команд\w*|скрипт\w*|запрос\w*|функци\w*|"
    r"алгоритм\w*|find|grep|regex|регуляр\w*|отсортиру\w*|напиш\w*)\b",
    re.IGNORECASE,
)


def _looks_like_hard_question(text: str) -> bool:
    return bool(
        _ALGO_TASK_RE.search(text) or _SITUATIONAL_HARD_RE.search(text) or _LETS_DO_HARD_RE.search(text)
    )



# Короткие "бэкчаннел"-реплики (кивки/поддакивания вроде "ага", "угу",
# "mm-hmm") сами по себе никогда не несут вопроса — но VAD режет их отдельной
# фразой транскрипта, точно как обычную реплику. Раньше (когда очередь
# подсказок была глубиной 1 и любой новый вопрос обрывал ещё не готовый ответ
# на предыдущий — см. историю у hint_request_queue в main()) ЛЮБАЯ новая
# строка транскрипта, даже такая, тут же помечала ещё считающийся ответ на
# ПРЕДЫДУЩИЙ, настоящий вопрос как устаревший, и запускала на неё же отдельный,
# заведомо бесполезный запрос к модели. На практике это стоило нам уже
# готового ответа на реальный вопрос ("что такое Stop Order?") — пока модель
# ходила в веб-поиск и генерировала ответ (это не быстро), собеседник успел
# сказать "Mm-hmm", и готовый ответ выкинули как устаревший вместо того чтобы
# показать. Очередь с тех пор стала FIFO и больше никого не обрывает и не
# выбрасывает (см. hint_request_queue), но фильтр остался: даже без обрыва
# каждая такая реплика — это лишний, заведомо бесполезный запрос к Ollama,
# который просто отнимает время у реальных вопросов в очереди. Игнорируем
# такие реплики целиком — не считаем их поводом ставить в очередь новый запрос.
# Фильтр поддакиваний ("ага", "ага, понятно") — см. text_filters.py.

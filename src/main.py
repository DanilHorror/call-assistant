@dataclass
class TagTouch:
    """
    Round 10O (см. проектный документ) — ОДНО обращение к теме: строка,
    которая его вызвала (question_line_index), и РЕАЛЬНЫЙ номер строки, куда
    фактически записался ответ (answer_line_index) — не "вопрос+1", как было
    раньше в _build_retrieved_context. Это различие не теоретическое: пока
    ответ ещё генерируется (секунда-две у GigaChat), разговор не стоит на
    паузе — кто угодно (собеседник ИЛИ сам пользователь) может успеть сказать
    что-то ещё, и эта чужая реплика встрянет МЕЖДУ вопросом и ответом в общем
    транскрипте. Старый код, вычислявший "ответ = вопрос+1", в этом случае
    решал бы, что ответа нет вообще, и терял его. Теперь answer_line_index
    получаем из РЕАЛЬНОГО возврата _finalize_hint_reply (см. main()/
    hint_worker) — там, где ответ реально дописывается в transcript_store, а
    не гадаем по позиции.

    answer_line_index — None, если ответ по какой-то причине не был записан в
    транскрипт (пустой reply — см. _finalize_hint_reply) — тогда при сборке
    retrieved_context показываем только вопрос, без выдуманной "ответной"
    строки.
    """

    question_line_index: int
    answer_line_index: int | None = None


@dataclass
class TrackedTag:
    """
    Один тег, накопленный за ТЕКУЩИЙ звонок (в отличие от judge.KnownTag —
    это не входные данные для судьи, а то, что реально хранится между
    вызовами). summary фиксируется в момент создания тега и больше не
    меняется, даже если тег потом "продолжают" — сознательный первый,
    самый простой вариант (без "эволюции" содержимого тега).

    last_line_index — номер строки в transcript_store.lines, где тег последний
    раз всплыл (создан или подтверждён продолжением). Используется ДВАЖДЫ: как
    база для пересчёта turns_ago перед следующим вызовом судьи, и как
    указатель для retrieval полного куска диалога (см. _build_retrieved_context
    ниже) — для обеих задач нужна именно СВЕЖЕСТЬ последнего упоминания, а не
    момент, когда тег впервые появился.

    embedding — смысловой вектор summary (см. embeddings.py), считается ОДИН
    РАЗ при создании тега. Нужен для _select_candidate_tags ниже: когда тегов
    накопилось много (длинный звонок — 20-60 вопросов), показывать судье
    ВЕСЬ список на каждый вызов означает неограниченно растущий промт (см.
    проектный документ) — вместо этого дешёво (без LLM, на CPU) находим
    несколько НАИБОЛЕЕ ПОХОЖИХ по смыслу тегов и показываем судье только их.
    None — если эмбеддинг посчитать не удалось (нет библиотеки/сети/и т.п.,
    см. embeddings.py) — тег в этом случае просто не участвует в отборе по
    смыслу, но остаётся доступен через отбор по свежести (см. ниже) и никуда
    не пропадает из хранилища.

    answer_embedding — Round 10M (см. проектный документ, "вариант Б" из
    обсуждения с пользователем), ОТДЕЛЬНЫЙ вектор — не для summary (вопроса-
    триггера), а для САМОГО ОТВЕТА, который реально показали пользователю по
    этой теме. Нужен для семантического recall — round 10L умеет находить
    точный старый ответ через _build_retrieved_context, но запускает это
    только по узкому regex ("повтори", "тот же" и т.п., см.
    _looks_like_repeat_request) — а перефразировку ("напомни, что ты там
    говорил про индексы") тот regex не ловит. answer_embedding позволяет
    решать это по СМЫСЛУ текущего вопроса против смысла старого ОТВЕТА, а не
    против ключевых слов во входящей фразе. В отличие от summary (фиксируется
    раз и навсегда), answer_embedding ОБНОВЛЯЕТСЯ при каждом касании тега —
    держит вектор САМОГО СВЕЖЕГО ответа, синхронно с last_line_index (см.
    _update_known_tags). None — как и с embedding выше, если посчитать не
    удалось (или ответа по этой теме ещё не было) — семантический recall для
    этого тега просто не участвует, тег продолжает жить как раньше.

    touches — Round 10O (см. проектный документ), по итогам разговора с
    пользователем: "хочу видеть РАЗВИТИЕ темы (были три правки кода — вот все
    три), а не только последний снимок". Список ВСЕХ обращений к теме за
    звонок (см. TagTouch выше), в хронологическом порядке — каждое хранит и
    ПРИЧИНУ (вопрос, вызвавший это обращение) и РЕЗУЛЬТАТ (реальный ответ).
    В отличие от last_line_index (одно число, только самое свежее) — ничего
    не перезаписывается, только добавляется, так что _build_retrieved_context
    может показать GigaChat всю цепочку "было так -> стало так -> стало
    так", а не только текущее состояние. Пользователь сознательно решил пока
    НЕ ограничивать длину этого списка ("пофиг на рост, будем тестировать") —
    так что промт по часто трогаемой теме может расти без потолка; это
    оставлено как открытый вопрос для реального теста, а не решено заранее.
    Не заполняется (остаётся пустым), если последняя попытка получить
    содержательный ответ провалилась технически (см. correction_failed в
    _update_known_tags) — не хотим засорять историю темы бесполезной
    отпиской вместо реального ответа.
    """

    tag: str
    summary: str
    last_line_index: int
    embedding: np.ndarray | None = None
    answer_embedding: np.ndarray | None = None
    touches: list[TagTouch] = field(default_factory=list)


# TrackedTag.summary = вся исходная фраза ЦЕЛИКОМ, без обрезки (см.
# _update_known_tags ниже — решение "самый простой вариант"). Это нормально
# для хранения, но небезопасно для показа судье НАПРЯМУЮ: посчитано точно
# (проектный документ "call-assistant: архитектура контекста", round 9,
# раздел про "прочность" JUDGE_NUM_CTX) — худший реалистичный случай на
# длинном звонке (9 тегов после _select_candidate_tags — top_k+recent_k —
# каждый с многословным summary, + 4 строки истории от _judge_history_text,
# + длинная текущая фраза) даёт ~3253 расчётных токена ПРОТИВ бюджета
# JUDGE_NUM_CTX=3072 — то есть переполнение, тем же механизмом, что чинили
# весь этот раунд, только с другой стороны (не сам промт судьи, а накопленные
# данные). Обрезка НИЖЕ применяется только к копии, которая идёт судье —
# полная фраза остаётся в TrackedTag.summary без изменений (сейчас нигде
# больше не используется, см. единственный вызов .summary в этом файле, но
# на будущее — не хотим тихо портить хранимые данные ради экономии токенов
# в одном конкретном вызове).
_JUDGE_SUMMARY_MAX_CHARS = 60


def _truncate_for_judge(text: str, max_chars: int = _JUDGE_SUMMARY_MAX_CHARS) -> str:
    if len(text) <= max_chars:
        return text
    return text[:max_chars].rstrip() + "…"


def _known_tags_for_judge(known_tags: list[TrackedTag], current_line_index: int) -> list[JudgeKnownTag]:
    """Пересчитывает turns_ago прямо перед вызовом судьи — сами TrackedTag
    хранят только last_line_index (абсолютный номер строки транскрипта), а не
    turns_ago, которое иначе пришлось бы обновлять у ВСЕХ тегов на каждой
    реплике, а не только у затронутых. summary обрезается до
    _JUDGE_SUMMARY_MAX_CHARS (см. комментарий выше про прочность num_ctx)."""
    return [
        JudgeKnownTag(
            tag=t.tag,
            summary=_truncate_for_judge(t.summary),
            turns_ago=current_line_index - t.last_line_index,
        )
        for t in known_tags
    ]


def _known_topics_for_gigachat(known_tags: list[TrackedTag], current_line_index: int) -> list[JudgeKnownTag]:
    """
    Round 10, рычаг 2 (см. проектный документ, "три рычага") — тот же список,
    что _known_tags_for_judge() выше, но БЕЗ обрезки summary до
    _JUDGE_SUMMARY_MAX_CHARS. Та обрезка была нужна конкретно для локального
    Ollama-судьи, зажатого JUDGE_NUM_CTX=3072 (см. комментарий у
    _JUDGE_SUMMARY_MAX_CHARS выше) — GigaChat не зажата тем же бюджетом
    контекста, и именно урезанные описания тем были одной из подозреваемых
    причин консолидации тегов и провалов сверхдальнего воспоминания (round 10:
    118 тем схлопнулись в 67, 6/6 провалов long_distance_recall). Переиспользуем
    JudgeKnownTag (из judge.py) как структуру данных, а не заводим отдельный
    дублирующий тип — этому полю всё равно нужны только .tag/.summary/.turns_ago,
    live_hints.py принимает их duck-typed (см. _format_known_topics там же).
    """
    return [
        JudgeKnownTag(
            tag=t.tag,
            summary=t.summary,
            turns_ago=current_line_index - t.last_line_index,
        )
        for t in known_tags
    ]


def _embed_for_recall(text: str) -> np.ndarray | None:
    """
    Round 10M — тонкая обёртка над embeddings.embed_text с тем же правилом
    терпимости к сбоям, что и везде в проекте (см. embeddings.py и
    _update_known_tags ниже): любая проблема (нет библиотеки/сети/модели) —
    просто None, вызывающий код обязан аккуратно пропустить семантическую
    часть, а не уронить живой звонок. Вынесено в отдельную функцию, потому что
    вызывается теперь из двух разных мест (_update_known_tags — для
    answer_embedding, hint_worker — для эмбеддинга ТЕКУЩЕГО вопроса перед
    сравнением).
    """
    try:
        return embeddings.embed_text(text)
    except Exception as e:
        print(f"[recall] не удалось посчитать embedding: {e}")
        return None


def _update_known_tags(
    known_tags: list[TrackedTag],
    verdict: JudgeVerdict,
    current_line_index: int,
    current_line_text: str,
    reply_text: str | None = None,
    answer_line_index: int | None = None,
    correction_failed: bool = False,
) -> None:
    """
    Обновляет список тегов ПОСЛЕ вердикта судьи. Вызывать только когда
    verdict.is_garbage == False (у "мусора" и tags, и continues_tags всегда
    пустые — вызов на нём безвреден, но бессмыслен). При ambiguous == True
    судья тоже возвращает оба списка пустыми (см. _JUDGE_SYSTEM_PROMPT) — то
    есть эта функция сама по себе корректно ничего не делает в этом случае,
    отдельная ветка не нужна.

    Одно правило вместо разбора по verdict.verdict: для каждого ИМЕНИ тега из
    объединения tags + continues_tags (при "продолжение" судья повторяет туда
    те же имена, что и в continues_tags) — если тег уже известен, обновляем
    только last_line_index (summary не трогаем, см. TrackedTag); если нет —
    заводим новый, summary = сама текущая фраза целиком (решение — самый
    простой вариант, без отдельного поля от судьи под summary), и заодно
    считаем embedding — один раз, здесь же, а не при каждом отборе кандидатов
    (см. _select_candidate_tags) — ошибка эмбеддинга (нет библиотеки/сети)
    НЕ должна ронять живой звонок, поэтому просто оставляем embedding=None и
    едем дальше: тег остаётся в списке, просто не будет участвовать в отборе
    по смыслу (только по свежести).

    Round 10M, необязательный reply_text: если передан (сейчас передаётся
    ТОЛЬКО из пути рычага 2, см. hint_worker — старый путь через судью не
    трогаем, чтобы не расширять эту правку туда, где её никто не просил) —
    считаем ЕЩЁ ОДИН, отдельный эмбеддинг для TrackedTag.answer_embedding (не
    путать с embedding выше — тот для summary/вопроса-триггера и меняется
    один раз при создании). answer_embedding, наоборот, ОБНОВЛЯЕТСЯ при
    каждом касании тега — держит вектор самого свежего ответа, синхронно с
    last_line_index. Если эмбеддинг не удалось посчитать — оставляем СТАРОЕ
    значение (если было) вместо None: одна неудачная попытка не должна
    выключать recall для всей темы целиком; ценой этого текст, который
    вектор представляет, в этот момент чуть разойдётся с last_line_index —
    не страшно, реальная защита от полного отказа важнее точной синхронности.

    Round 10O — два новых параметра по итогам разговора с пользователем:

    answer_line_index — РЕАЛЬНЫЙ номер строки, куда фактически записался
    ответ (см. TagTouch/_finalize_hint_reply — она теперь возвращает этот
    номер, а не угадывается как "current_line_index+1"). Используется для
    новой записи в TrackedTag.touches.

    correction_failed — True, только если рычаг 2 ПЫТАЛСЯ сделать уточняющий
    вызов с retrieved_context и он упал технически (сеть, таймаут — см.
    hint_worker, except-блок вокруг второго вызова). В этом случае reply,
    который сюда передан — черновик ПЕРВОГО вызова (честный, но без
    реального содержания темы, часто просто "мы это обсуждали, показать
    новый вариант?") — если запомнить его в touches/answer_embedding как
    "то, что мы теперь знаем по этой теме", СЛЕДУЮЩЕЕ обращение к теме
    получит эту бесполезную отписку ВМЕСТО настоящего старого ответа —
    настоящий контент из истории тега потеряется навсегда. Поэтому при
    correction_failed=True: last_line_index ВСЁ РАВНО обновляется (тема
    реально была затронута сейчас, это факт свежести, а не содержания), но
    НИЧЕГО не добавляется в touches и answer_embedding НЕ трогается —
    условие чисто механическое ("сетевой вызов технически упал"), а не
    попытка оценить качество текста самого ответа.
    """
    names = list(dict.fromkeys([*verdict.tags, *verdict.continues_tags]))
    by_name = {t.tag: t for t in known_tags}
    for name in names:
        existing = by_name.get(name)
        if existing is not None:
            existing.last_line_index = current_line_index
            if not correction_failed:
                existing.touches.append(
                    TagTouch(question_line_index=current_line_index, answer_line_index=answer_line_index)
                )
                if reply_text:
                    new_answer_embedding = _embed_for_recall(reply_text)
                    if new_answer_embedding is not None:
                        existing.answer_embedding = new_answer_embedding
        else:
            embedding = None
            try:
                embedding = embeddings.embed_text(current_line_text)
            except Exception as e:
                print(f"[tags] не удалось посчитать embedding для тега {name!r}: {e}")
            answer_embedding = (
                _embed_for_recall(reply_text) if (reply_text and not correction_failed) else None
            )
            initial_touches = (
                []
                if correction_failed
                else [TagTouch(question_line_index=current_line_index, answer_line_index=answer_line_index)]
            )
            new_tag = TrackedTag(
                tag=name,
                summary=current_line_text,
                last_line_index=current_line_index,
                embedding=embedding,
                answer_embedding=answer_embedding,
                touches=initial_touches,
            )
            known_tags.append(new_tag)
            by_name[name] = new_tag


# Пока known_tags короче этого порога, судья видит ВЕСЬ список как раньше —
# ничего не меняется для короткого/обычного разговора (и для всех уже
# провалидированных кейсов в data/judge_test_cases.json, там максимум 3 тега).
# Отбор кандидатов (дороже считать, и по смыслу может ошибиться на редких
# синонимах — см. embeddings.py) включается только когда список ДЕЙСТВИТЕЛЬНО
# грозит раздуть промт: длинный звонок на 20-60 вопросов может накопить
# сравнимое количество тегов, и тогда полный список сам по себе становится
# сопоставим по размеру с (и без того тесным) системным промтом судьи.
_TAG_SELECTION_THRESHOLD = 10
_TAG_SELECTION_TOP_K = 6
_TAG_SELECTION_RECENT_K = 3


def _select_candidate_tags(
    known_tags: list[TrackedTag],
    current_line_text: str,
    threshold: int = _TAG_SELECTION_THRESHOLD,
    top_k: int = _TAG_SELECTION_TOP_K,
    recent_k: int = _TAG_SELECTION_RECENT_K,
) -> list[TrackedTag]:
    """
    Возвращает подмножество known_tags, которое реально показываем судье.
    Ничего не удаляется из ХРАНИЛИЩА (known_tags в main() остаётся полным на
    весь звонок) — это только то, что попадёт в ОДИН конкретный промт.

    top_k самых похожих по смыслу (embedding, см. embeddings.py) + recent_k
    самых свежих по last_line_index — ОБЪЕДИНение (не либо/либо): смысловой
    поиск может не найти совпадение на короткой фразе без содержательных слов
    ("приведи примеры") — туда и нужна подстраховка по свежести; а свежесть
    сама по себе может пропустить тег, который правда нужен, но давно не
    всплывал. Раз объединяем, а не выбираем одно — на практике это либо
    ~top_k+recent_k тегов, либо меньше (пересечение).

    Если embedding текущей фразы посчитать не удалось (см. embeddings.py) —
    откатываемся к ПОЛНОМУ списку (лучше временно вернуть промт-переполнение,
    какое было и раньше, чем молча потерять кандидата, который нужен именно
    сейчас).
    """
    if len(known_tags) <= threshold:
        return known_tags

    try:
        query_embedding = embeddings.embed_text(current_line_text)
    except Exception as e:
        print(f"[tags] не удалось посчитать embedding текущей фразы, показываю судье все теги: {e}")
        return known_tags

    scored = [
        (embeddings.cosine_sim(query_embedding, t.embedding), t) for t in known_tags if t.embedding is not None
    ]
    scored.sort(key=lambda pair: pair[0], reverse=True)
    by_similarity = [t for _, t in scored[:top_k]]

    by_recency = sorted(known_tags, key=lambda t: t.last_line_index, reverse=True)[:recent_k]

    combined: list[TrackedTag] = []
    seen_ids: set[int] = set()
    for t in [*by_similarity, *by_recency]:
        if id(t) not in seen_ids:
            seen_ids.add(id(t))
            combined.append(t)

    # Round 10g (см. проектный документ) — ВАЖНО: порядок, в котором combined
    # уходит дальше (в _known_tags_for_judge/_known_topics_for_gigachat, а
    # оттуда прямо построчно в промт — см. judge._format_known_tags /
    # live_hints._format_known_topics), раньше был "сначала top_k по
    # похожести, потом recent_k по свежести" — то есть тег, найденный ТОЛЬКО
    # через recency (а не через embedding), всегда оказывался в САМОМ КОНЦЕ
    # списка, даже если это буквально последняя обсуждённая тема. На реальном
    # GigaChat (round 10f/10g, свежий stress_test_v2, 8/8 ambiguous_backref)
    # это совпало с систематической путаницей: на расплывчатые отсылки назад
    # ("вернёмся к твоему примеру"), где embedding-сходство по сути шум (в
    # самой фразе нет содержательных слов), модель раз за разом называла НЕ
    # два реально ближайших по времени кандидата, а темы из середины/начала
    # списка — то есть темы, отобранные по похожести, а не по свежести.
    # Пересортировка по last_line_index (самые свежие — ПЕРВЫМИ в списке) не
    # меняет СОСТАВ кандидатов (тот же union top_k+recent_k), только порядок
    # показа — а для расплывчатой отсылки именно порядок ("что было последним
    # по времени") и есть основной сигнал, который стоит подсвечивать первым.
    # Не удаляет и не меняет отбор — чисто сортировка перед возвратом.
    combined.sort(key=lambda t: t.last_line_index, reverse=True)
    return combined


# Судье для разбора ТЕКУЩЕЙ фразы (местоимения, короткие ответы на только что
# заданный уточняющий вопрос — см. проектный документ) нужно от силы пара
# последних реплик, а не HINTS_CONTEXT_LINES=20, который выбран под нужды
# ГЕНЕРАТОРА ответа, а не судьи. Реальный тест на живом GigaChat-пути показал,
# что при 8 строках истории (а с HINTS_CONTEXT_LINES=20 их может быть куда
# больше) промт судьи ощутимо превышает num_ctx=2048 и модель начинает вести
# себя непредсказуемо (см. проектный документ, round 7/7b) — долгосрочная
# память тем и так уже есть отдельно (known_tags), сырая история судье нужна
# только на разбор непосредственно текущей фразы.
_JUDGE_HISTORY_LINES = 4


def _judge_history_text(
    transcript_store: TranscriptStore, current_line_index: int, max_lines: int = _JUDGE_HISTORY_LINES
) -> str:
    """
    Строки СТРОГО до current_line_index (сама текущая фраза сюда не входит —
    она уходит в classify_utterance() отдельным параметром current_line).
    Берём срез напрямую из transcript_store.lines по индексу, а не из уже
    готового recent_text/history_text (посчитанного в process_loop под
    HINTS_CONTEXT_LINES) — так надёжнее: line_index зафиксирован на момент
    постановки в очередь и не сдвинется, даже если к моменту, когда hint_worker
    реально дойдёт до этого запроса, в transcript_store уже добавились более
    новые строки (список только растёт в конец, старые индексы не меняются).
    """
    start = max(0, current_line_index - max_lines)
    lines = transcript_store.lines[start:current_line_index]
    return "\n".join(f"{line.speaker}: {line.text}" for line in lines)


# Round 10L (см. проектный документ) — "вариант 2" из обсуждения с
# пользователем: явные просьбы буквально ПОВТОРИТЬ уже прозвучавший ответ
# ("тот же пример", "повтори", "помнишь... ты делал/приводил") — НЕ то же
# самое, что просьба получить НОВЫЙ/другой пример ("ещё один пример", "а с
# другим", "посложнее") — те специально НЕ ловим здесь, они хотят другое
# содержимое, не буквальный повтор старого, и рычаг 2 и так неплохо с ними
# справляется генерируя новый пример по теме. Структурная эвристика в духе
# рычага 1 (regex, без похода к модели) — дёшево решает, стоит ли платить
# ВТОРЫМ сетевым вызовом ради honest retrieval (см. _looks_like_repeat_request
# ниже и место вызова в hint_worker).
_REPEAT_REQUEST_RE = re.compile(
    r"(помнишь|повтори|дословно|тот\s+же|тот\s+самый|та\s+же|такой\s+же|"
    r"снова[^.!?]{0,15}?(?:этот|тот|такой)|"
    r"ты\s+(?:уже\s+)?(?:делал|приводил|показывал|писал|говорил|называл)\b)",
    re.IGNORECASE,
)


def _looks_like_repeat_request(text: str) -> bool:
    """
    Живой кейс, из-за которого это появилось (см. проектный документ, round
    10L): рычаг 2 в один вызов помнит только НАЗВАНИЕ темы (TrackedTag.summary
    — исходная фраза, которая подняла тему), а не сам сгенерированный ответ.
    Через 40+ реплик оригинальный текст (например код примера с JOIN) выпадает
    и из видимого окна транскрипта (HINTS_CONTEXT_LINES), и из короткого
    own_answers — получается честное, но бесполезное "мы это обсуждали, хотите
    новый пример?" вместо буквального повтора старого. Не пытаемся угадать
    ВСЕ формулировки — как и везде в проекте, это первая версия эвристики,
    ожидающая уточнения на реальных звонках.
    """
    return bool(_REPEAT_REQUEST_RE.search(text.lower()))


def _build_retrieved_context(
    continues_tags: list[str],
    known_tags: list[TrackedTag],
    transcript_store: TranscriptStore,
) -> str:
    """
    Round 10O (см. проектный документ) — переписано по итогам разговора с
    пользователем: раньше собирался только ОДИН, самый свежий обмен репликами
    (по last_line_index, с угадыванием "ответ = вопрос+1" — см. историю
    находки бага в проектном документе: угадывание ломалось, если между
    вопросом и ответом успевала проскочить ещё чья-то реплика, пока ответ ещё
    генерировался). Теперь используется TrackedTag.touches — полная,
    хронологическая история ВСЕХ обращений к теме, каждое со СВОИМ реальным
    (не угаданным) номером строки ответа — так GigaChat видит не только
    текущее состояние, а как к нему пришли ("было так -> стало так -> стало
    так"), и может корректно обработать не только "повтори", но и "доработай
    то, что уже было" (реальный кейс с SQL+JOIN+ORDER BY, обсуждённый с
    пользователем).

    ВАЖНО, как и раньше: если функция вызывается ДО _update_known_tags для
    ТЕКУЩЕГО обращения — текущий (ещё не отвеченный) вопрос физически не
    может быть в touches (он туда попадёт только ПОСЛЕ того, как ответ будет
    готов) — так что беспокоиться о вызове "до или после" относительно этого
    конкретного вызова уже не нужно так строго, как со старым last_line_index
    (который перезаписывался, а не пополнялся) — но по-прежнему вызываем ДО,
    для ясности и на случай будущих изменений.

    Пользователь сознательно решил ПОКА НЕ ограничивать длину touches
    ("пофиг на рост, будем тестировать") — если реальный звонок покажет, что
    промт по часто трогаемой теме раздувается заметно, это открытый вопрос
    для отдельного раунда, а не решённый заранее потолок.
    """
    by_name = {t.tag: t for t in known_tags}
    blocks = []
    for name in continues_tags:
        tracked = by_name.get(name)
        if tracked is None or not tracked.touches:
            continue
        pieces = []
        for i, touch in enumerate(tracked.touches, start=1):
            q_idx = touch.question_line_index
            if q_idx < 0 or q_idx >= len(transcript_store.lines):
                continue
            q_line = transcript_store.lines[q_idx]
            piece = f"{i}) {q_line.speaker}: {q_line.text}"
            a_idx = touch.answer_line_index
            if a_idx is not None and 0 <= a_idx < len(transcript_store.lines):
                a_line = transcript_store.lines[a_idx]
                # Проверка speaker — на случай, если answer_line_index
                # почему-то указывает не туда (защита не должна ронять
                # звонок даже при непредвиденной рассинхронизации).
                if a_line.speaker == "Ассистент":
                    piece += f"\n   {a_line.speaker}: {a_line.text}"
            pieces.append(piece)
        if pieces:
            blocks.append(f"История темы «{name}» (как она менялась):\n" + "\n".join(pieces))
    return "\n\n".join(blocks)


def _semantic_recall_score(question_embedding: np.ndarray | None, tag: TrackedTag) -> float | None:
    """
    Round 10M ("вариант Б") — косинусная похожесть между эмбеддингом ТЕКУЩЕГО
    вопроса и tag.answer_embedding (эмбеддинг САМОГО СВЕЖЕГО ответа по этой
    теме, см. TrackedTag/_update_known_tags). Задача та же, что у
    _looks_like_repeat_request выше, но по-другому: тот ловит буквальные слова
    во входящей фразе ("повтори", "тот же"), этот — смысловую похожесть,
    независимо от формулировки ("напомни, что ты говорил про индексы" — без
    единого слова "повтори" — тоже должно найтись, если ответ про индексы
    действительно был).

    ВАЖНО, честно про ограничение: embeddings.embed_text() обрезает текст до
    64 токенов (см. embeddings.py) — на длинном ответе (например SQL-пример на
    несколько строк) эмбеддинг реально считается только по началу ответа
    (обычно вступление + начало кода). На практике вступление почти всегда
    отражает суть темы ("вот пример запроса с JOIN..."), так что для ЗАДАЧИ
    "тот же ли это ТОПИК" это должно быть достаточно — но на этапе разработки
    проверялось на хэш-заглушке вместо настоящей модели, поэтому решение
    "работает ли это качественно" остаётся за реальным прогоном на устройстве.

    Возвращает None, если эмбеддинг вопроса не посчитан или у тега ещё нет
    answer_embedding (ответа по этой теме ещё не было, либо эмбеддинг не
    удалось посчитать ни разу) — вызывающий код должен трактовать None как
    "сигнала нет", а не как "похожесть 0".
    """
    if question_embedding is None or tag.answer_embedding is None:
        return None
    try:
        return embeddings.cosine_sim(question_embedding, tag.answer_embedding)
    except Exception as e:
        print(f"[recall] не удалось посчитать похожесть: {e}")
        return None


def _resolve_gigachat_cascade(starting_model: str, cascade: list[str]) -> list[str]:
    """
    Round 11 (см. проектный документ) — с какой модели GigaChat реально
    начинать перебор при исчерпании токенов (main()/hint_worker/
    _call_gigachat_cascaded вызывают это как первый шаг). Вынесена на
    уровень модуля (а не как раньше — вложенной функцией внутри main())
    специально, чтобы её можно было проверить автономным тестом
    (test_reply_pool.py), не поднимая весь main() с аудио/GUI/сетью —
    сама функция чистая, никакого состояния звонка не трогает.

    Начинаем каскад с той модели, что и так уже решил hint_worker
    (settings.gigachat_model для сложных вопросов / gigachat_normal_model
    для остальных) — а не всегда с самой сильной: если обычный вопрос
    изначально идёт на более лёгкую модель, при её 402 логично пробовать
    СЛЕДУЮЩУЮ ПО СПИСКУ после неё, а не начинать каскад заново с Ultra.
    Если starting_model почему-то не найдена в cascade (например .env
    переопределил gigachat_model на что-то вне каскада) — честно ставим
    её первой самостоятельным элементом, а дальше пробуем полный каскад
    как запасной вариант, а не падаем.
    """
    if starting_model in cascade:
        idx = cascade.index(starting_model)
        return cascade[idx:]
    return [starting_model, *cascade]



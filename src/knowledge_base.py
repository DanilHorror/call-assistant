_WORD_RE = re.compile(r"[a-zа-яё0-9]+", re.IGNORECASE)


# Простейший стемминг: длинные слова обрезаются до первых _STEM_LEN букв,
# чтобы разные формы одного слова совпадали ("подключиться" / "подключении",
# "отключили" / "отключить"). Без морфологического анализатора и зависимостей:
# для короткой тематической базы этого достаточно.
_STEM_LEN = 6


def _stem(word: str) -> str:
    word = word.replace("ё", "е")
    return word[:_STEM_LEN] if len(word) > _STEM_LEN else word


def _tokenize(text: str) -> set[str]:
    words = _WORD_RE.findall(text.lower())
    return {_stem(w) for w in words if len(w) >= 2 and w not in _STOPWORDS}


def load_kb(path: str | Path) -> list[dict]:
    """
    Загружает базу знаний из JSON-файла: список объектов
    {"question": str, "answer": str, "section": str (опционально)}.
    Пустой список, если файл не найден/битый — не должно ронять подсказки,
    просто база знаний в этом случае не используется.
    """
    p = Path(path)
    try:
        with p.open(encoding="utf-8") as f:
            data = json.load(f)
        if not isinstance(data, list):
            raise ValueError("ожидался список объектов")
        return data
    except Exception as e:
        print(f"[kb] не удалось загрузить базу знаний '{path}': {e}")
        return []


# Кэш "частоты слов по вопросам базы" — считается один раз на объект kb (не на
# каждый поиск), ключ — id() списка. Это безопасно, поскольку в live_hints.py
# один и тот же объект kb переиспользуется из собственного кэша по пути к
# файлу (см. _KB_CACHE / _get_kb) на всё время работы процесса.
_DOC_FREQ_CACHE: dict[int, tuple[dict[str, int], int]] = {}


def _get_doc_freq(kb: list[dict]) -> tuple[dict[str, int], int]:
    key = id(kb)
    cached = _DOC_FREQ_CACHE.get(key)
    if cached is None:
        df: dict[str, int] = {}
        for item in kb:
            for w in _tokenize(item.get("question", "")):
                df[w] = df.get(w, 0) + 1
        cached = (df, len(kb))
        _DOC_FREQ_CACHE[key] = cached
    return cached


def _idf(word: str, df: dict[str, int], n_docs: int) -> float:
    # Сглаженный IDF: слово, которого нет ни в одном вопросе базы, всё равно
    # получает какой-то вес (не ноль) — чтобы редкие термины из текущей фразы,
    # которых в базе почти нет, не обнулялись целиком.
    return math.log((n_docs + 1) / (df.get(word, 0) + 1)) + 1.0


def search_kb(query: str, kb: list[dict], top_k: int = 3, min_score: float = 0.15) -> list[dict]:
    """
    Возвращает до top_k записей из kb, наиболее похожих на query, с полем
    "score" (0..~1.3), отсортированных по убыванию. Записи со score ниже
    min_score отбрасываются — лучше не показать ничего, чем притянуть за
    уши нерелевантную карточку.

    Совпадение взвешивается по редкости слова (IDF) — так короткий запрос
    вроде "сколько уровней в модели OSI?" не притягивает все карточки со
    словом "модели" (оно есть в десятках вопросов базы), а действительно
    реагирует на редкое и потому значимое "osi".
    """
    query_words = _tokenize(query)
    if not query_words:
        return []

    df, n_docs = _get_doc_freq(kb)
    query_idf_sum = sum(_idf(w, df, n_docs) for w in query_words) or 1.0
    query_lower = query.lower()

    scored = []
    for item in kb:
        question = item.get("question", "")
        answer = item.get("answer", "")
        q_words = _tokenize(question)
        if not q_words:
            continue
        overlap = query_words & q_words
        if not overlap:
            continue
        overlap_idf = sum(_idf(w, df, n_docs) for w in overlap)
        score = overlap_idf / query_idf_sum
        # Слова запроса, которых нет в вопросе карточки, но есть в её ответе,
        # дают половинный вес: "подключиться на год — есть скидка?" находит
        # карточку "Есть ли скидка для новых абонентов?", в ОТВЕТЕ которой
        # сказано "при подключении на год". Карточка учитывается, только если
        # совпало хотя бы одно слово самого вопроса (проверка выше).
        answer_only = (query_words - overlap) & _tokenize(answer)
        if answer_only:
            score += 0.5 * sum(_idf(w, df, n_docs) for w in answer_only) / query_idf_sum
        # Небольшой бонус, если формулировка вопроса из базы почти целиком
        # содержится в текущей фразе как подстрока (частый случай, когда
        # собеседник почти дословно цитирует термин).
        if question.lower().strip("?. ") in query_lower:
            score += 0.3
        if score >= min_score:
            scored.append(
                {"question": question, "answer": answer, "section": item.get("section", ""), "score": round(score, 3)}
            )

    scored.sort(key=lambda x: x["score"], reverse=True)
    return scored[:top_k]


def format_kb_for_prompt(results: list[dict]) -> str:
    """
    Форматирует найденные записи в текстовый блок для промпта — тот же
    стиль нумерованного списка, что и format_results_for_prompt в
    web_search.py, для единообразия.
    """
    if not results:
        return ""
    lines = [f"{i}. Вопрос: {r['question']}\n   Ответ: {r['answer']}" for i, r in enumerate(results, 1)]
    return "\n".join(lines)

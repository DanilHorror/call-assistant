"""
Локальная база знаний для live-подсказок: заранее подготовленные пары
вопрос/ответ (например, справочник для оператора), по которым можно
искать релевантные записи под текущую фразу собеседника — вместо того
чтобы полагаться только на "сырые" знания модели или ходить в веб-поиск.

Зачем это отдельно от web_search.py: веб-поиск — это НЕПРОВЕРЕННЫЙ внешний
источник (сниппеты выдачи), который используется как последний резерв для
быстро меняющихся фактов. База знаний — наоборот, ЗАРАНЕЕ подготовленный
пользователем набор проверенных пар "вопрос-ответ" на конкретную тему
(например, справочник по конкретному продукту или услуге) — если по
текущей фразе нашлось явное совпадение, это куда более надёжный источник,
чем догадка модели или сниппет поисковика.

Поиск сделан намеренно простым (без embeddings/векторной базы и внешних
ML-библиотек): нормализация текста + пересечение слов, взвешенное по
редкости слова (упрощённый TF-IDF: чем реже слово встречается в вопросах
базы знаний, тем больше оно значит для совпадения — иначе короткие запросы
вроде "сколько уровней в модели OSI?" силой притягивают все карточки со
словом "модели", а не только реально релевантную про OSI) + бонус за точное
вхождение фразы. Этого достаточно для сравнительно короткого текущего
вопроса против конкретной, тематически узкой базы карточек — и это легко
отлаживать/подкручивать вручную (см. --kb-debug флаг в test_hint.py), без
чёрного ящика векторной модели.
"""
from __future__ import annotations

import json
import math
import re
from pathlib import Path

# Частые русские (и немного английских) служебные слова — не несут
# различающего смысла для поиска, только шумят в пересечении множеств слов.
# Однокоренные технические аббревиатуры из 2 букв (QA, QC, UI, UX, DB, OS...)
# сюда НЕ добавляем — в этой предметной области они как раз самые значимые

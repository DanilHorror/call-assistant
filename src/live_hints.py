# Кэш загруженных баз знаний по пути к файлу — сам JSON читается с диска
# только один раз за всё время работы процесса (а не на каждую фразу
# собеседника), парсится и хранится в памяти.
_KB_CACHE: dict[str, list[dict]] = {}

def _get_kb(path: str) -> list[dict]:
    if path not in _KB_CACHE:
        _KB_CACHE[path] = load_kb(path)
        print(f"[kb] загружено {len(_KB_CACHE[path])} записей из '{path}'")
    return _KB_CACHE[path]


def _log_kb_matches(query: str, matches: list[dict], min_score: float) -> None:
    """Печатает, какие карточки базы знаний нашлись под текущую фразу —
    чтобы по логу было видно, отвечала модель по базе или от себя."""
    if matches:
        found = "; ".join(f"{m['question']!r}~{m['score']}" for m in matches)
        print(f"[kb] найдено (порог {min_score}): {found}")
    else:
        print(f"[kb] по фразе {query[:60]!r} в базе ничего не найдено (порог {min_score})")


def preload_kb(path: str) -> None:
    """
    Прогревает кэш базы знаний ДО начала звонка — та же идея, что и у
    warmup_model() для модели Ollama. Без этого JSON с базой знаний (может
    быть сотни записей) парсился с диска лениво, внутри generate_hint(), в
    момент обработки САМОГО ПЕРВОГО вопроса звонка — то есть первый вопрос
    получал лишнюю задержку (а на медленном диске/большой базе — риск
    вылезти за тайм-аут подсказки) просто из-за случайности "кто первый
    попросил базу". Зовём это явно и заранее, пока звонок ещё не начался и
    пользователь не ждёт ответ на конкретный вопрос.
    """
    try:
        _get_kb(path)
    except Exception as e:
        print(f"[kb] не удалось предзагрузить базу знаний: {e}")


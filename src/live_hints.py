# Сигнал конца ответа, которым мы просим модель заканчивать вывод (см. промпты
# выше) — передаём его же как стоп-слово в Ollama, чтобы генерация физически
# обрывалась на нём, а не полагаться только на послушание модели.
_STOP_MARKER = "###"

# Даже если модель проигнорирует "###" — правдоподобно смещается в мусор не
# сразу: сначала честно отвечает, потом иногда продолжает "объяснять сама
# себе" остаток промпта, включая скатывание в китайский (Qwen обучен и на
# китайском тоже). Всё, что похоже на такой мусор, обрезаем на нашей стороне.
_CJK_RUN = re.compile(r"[一-鿿぀-ヿ가-힯].*", re.DOTALL)

# Другой вид того же "съезда в мусор" — не целый чужой алфавит, а слово, где
# кириллица и латиница слиплись БЕЗ РАЗДЕЛИТЕЛЯ, впритык, посреди слова
# (например "ЛисиONUS", "Алuminium") — это надёжный признак порчи. НО обычные
# русские технические термины с дефисом ("V-модель", "IT-компания",
# "QA-инженер", "A-класс") — это ТОЖЕ кириллица+латиница в одном "слове" по
# пробелам, но легитимные: там между алфавитами есть дефис, а не прямая
# склейка букв. Раньше regex не различал эти два случая и вырезал "V-модель"
# как будто это порча — теряя подлежащее из корректного ответа. Теперь матчим
# только НЕПОСРЕДСТВЕННОЕ соседство кириллицы и латиницы (без дефиса/пробела
# между ними) — так остаются целыми "V-модель" и т.п., но "Алuminium" и
# "ЛисиONUS" всё ещё ловятся.
_MIXED_SCRIPT_WORD = re.compile(
    r"\S*[А-Яа-яЁё][A-Za-z]\S*|\S*[A-Za-z][А-Яа-яЁё]\S*"
)

# Ещё один вид порчи, пойманный на практике: модель может съехать на соседний
# славянский язык прямо посреди русского текста — не перепутать буквы, а
# натурально произвести слово ДРУГОГО языка (например "тестированије
# безбедности" вместо "тестирования безопасности" — "безбедност" это не
# опечатка, а настоящее сербское слово "безопасность"). В отличие от
# слипшейся кириллицы+латиницы это не проблема кодировки, а языковой дрейф —
# но его легко ловить по буквам, которых в русском алфавите просто нет:
# сербские ђ/ј/љ/њ/ћ/џ и украинские і/ї/є/ґ. Если слово содержит хоть одну
# такую букву — это гарантированно не русское слово. В отличие от
# _MIXED_SCRIPT_WORD выше здесь риска ложного срабатывания на легитимный
# русский технический термин нет вообще (этих букв в русском попросту не
# существует), поэтому вырезаем сразу, без "временно отключено".
_FOREIGN_CYRILLIC_WORD = re.compile(r"\S*[іїєґђјљњћџІЇЄҐЂЈЉЊЋЏ]\S*")

# Было 400, потом 900, потом 1300 — но и 1300 всё ещё срезает самые крупные
# случаи. На полном прогоне всех 515 вопросов через batch_test_followup.py
# при 900 обрублена была только 1 строка из 515 (было 8 из 171 при 400) —
# "Назовите все 7 принципов тестирования" + "расскажи о каждом из них
# подробнее" (7 пунктов с пояснением каждый — самый крупный список во всей
# базе). Значит реальный потолок задаёт не эта страховка, а num_predict/
# max_tokens (см. _call_ollama и llm_gigachat._MAX_TOKENS).
#
# Round 11 (см. проектный документ): изначальное число 2200 было откалибровано
# ИМЕННО под слабую локальную Ollama (gemma2:9b/qwen2.5:7b) — под её
# num_predict=1500 и под реально наблюдавшийся у неё "CJK-побег" (генерация
# вдруг съезжает в посторонний алфавит). Пользователь явно решил полностью
# отказаться от Ollama как от фолбэка ("этот костыль нужен был для слабой
# модели Ollama, GigaChat не нужна эта защита") и поднять потолок до 8192
# символов — величина осознанно выбрана вровень с окном эмбеддинг-модели
# deepvk/USER-bge-m3 (см. embeddings.py, round 11), под которую теперь
# целиком эмбеддятся ответы ассистента (а не только начало, как раньше с
# rubert-tiny2 и её 64 токенами) — то есть этот потолок теперь одновременно
# служит и защитой от совсем уж вырожденной генерации (см. CJK-проверку
# чуть выше, она никуда не делась), и практической гарантией, что ответ
# гарантированно влезет в эмбеддинг без обрезки. Сама страховка (проверка
# длины + CJK-обрыв) НЕ убрана — только предел поднят, ЛОГИКА защиты не
# менялась.
_MAX_FIELD_LEN = 8192

# Регэксп для удаления метки говорящего ("Собеседник: ", "Собеседник 2: ",
# "Я: ") из фразы ПЕРЕД тем, как отдавать её в search_kb(). Без этого слово
# "собеседник" само становится токеном запроса (IDF у него огромный — оно
# не встречается вообще ни в одном вопросе базы) и ЗАНИЖАЕТ score вообще
# ВСЕХ запросов на пустом месте (проверено эмпирически: "Что такое Test
# Closure?" дословно совпадает с вопросом базы и должен давать 1.3, но с
# оставленной меткой даёт только 0.899 — просто из-за лишнего слова
# "собеседник" в знаменателе доли). Обнаружено при попытке откалибровать
# порог ниже: пороговое значение считалось на тестах БЕЗ метки, а реальный
# current_line (см. _split_current_line) метку всегда содержит — из-за
# этого первая версия порога (1.05) была теоретически недостижима в
# реальной работе и отсекала бы вообще любые совпадения на продолжении,
# включая честные.
_SPEAKER_LABEL_RE = re.compile(r"^(?:Я|Собеседник(?:\s+\d+)?|Ассистент)\s*:\s*")

# Порог совпадения с базой знаний на вопросе-ПРОДОЛЖЕНИИ (own_answers
# непустой — см. generate_hint). Пойман на массовом прогоне
# batch_test_followup.py: короткая обобщённая формулировка вроде "как это
# применяется на практике?" или "почему это вообще важно?" почти не несёт
# собственной темы, и по чистому пересечению слов (search_kb — IDF, без
# смысла) может случайно "найти" СОВЕРШЕННО не связанную запись из базы
# (например про Percy/визуальное тестирование или форекс-хеджирование —
# вместо реального продолжения разговора), а код при этом безусловно
# доверяет любому найденному kb_block больше, чем own_answers.
#
# Разбор формулы search_kb() (knowledge_base.py): score = (доля слов
# запроса, найденных в вопросе базы) + бонус 0.3, если ВЕСЬ вопрос базы
# (без "?.") целиком входит в запрос подстрокой. Проверено эмпирически:
# прогнали ВСЕ 15 реальных шаблонов уточняющих вопросов (gen_followups.py)
# против ВСЕХ 515 вопросов базы (после удаления метки говорящего, см.
# _SPEAKER_LABEL_RE выше) — худшее случайное совпадение дало 0.618
# ("Почему это вообще важно?" против не связанного по теме вопроса про
# отзыв в блоге компании). Настоящее почти-дословное повторение вопроса
# базы (единственный случай, когда бонус +0.3 реально применяется) даёт
# 1.0-1.3. Порог 0.75 лежит с запасом выше худшего случайного совпадения
# (0.618) и с запасом ниже любого настоящего почти-дословного совпадения
# (1.0+) — в отличие от первой версии (1.05), которая была откалибрована
# без учёта метки говорящего и на практике блокировала бы вообще все
# совпадения, а не только ложные.
# Публичная версия: база знаний маленькая и тематическая (демо-справочник
# оператора), а поиск учитывает формы слов и текст ответа (см.
# knowledge_base.py). Перепроверено на наборе "целевые вопросы vs общие
# уточнения": целевые продолжения ("а если на год, есть скидка?") дают 0.6-0.7,
# случайные совпадения общих уточнений — до ~0.46. Порог 0.5 между ними;
# можно переопределить в .env (KB_CONTINUATION_MIN_SCORE).
_CONTINUATION_KB_MIN_SCORE = float(os.getenv("KB_CONTINUATION_MIN_SCORE", "0.5"))


def _clean_field(text: str) -> str:
    """
    Защита от "убежавшей" генерации — но два разных вида порчи лечатся
    по-разному, раз выяснили это на практике:
    - Скатывание в китайский — это обычно обвал генерации целиком (модель
      уже не остановилась и продолжает писать что попало), и до конца текста
      восстановить нечего — режем всё, что после начала такого прогона.
    - А слово, где кириллица слиплась с латиницей без пробела (например
      "ЛисиONUS") — обычно сбой на уровне ОДНОГО слова, а не всей генерации:
      текст до и после него часто нормальный и осмысленный. Раньше резали
      всё, что после такого слова, и один реальный случай ("Алuminium" в
      самом начале иначе правильного ответа про алюминий) из-за этого терял
      весь ответ целиком, хотя дальше шёл верный текст. Теперь вырезаем
      только само слово, а не всё, что после него.
    """
    text = text.split(_STOP_MARKER, 1)[0]  # если маркер всё же проскочил в текст поля
    m = _CJK_RUN.search(text)
    if m:
        text = text[: m.start()]
    # ВРЕМЕННО отключено: после того как выяснилось, что старая версия этого
    # regex съедала легитимные слова вроде "V-модель", решили не резать
    # слипшиеся кириллица+латиница слова вообще, пока не наберём больше
    # живых примеров и не убедимся, что исправленный regex (см. выше,
    # _MIXED_SCRIPT_WORD) больше не задевает ничего настоящего. Сам regex
    # уже поправлен (ловит только прямую склейку без дефиса), просто пока
    # перестраховываемся и не применяем его.
    # text = _MIXED_SCRIPT_WORD.sub(" ", text)
    text = _FOREIGN_CYRILLIC_WORD.sub(" ", text)
    text = re.sub(r"\s{2,}", " ", text).strip()
    if len(text) > _MAX_FIELD_LEN:
        text = text[:_MAX_FIELD_LEN].rstrip() + "…"
    return text


# Ищем "ОТВЕТ:" не буквально, а с допуском на русские окончания (модель может
# написать "ОТВЕТА:", "ОТВЕТЫ:" и т.п. вместо словарной формы) — на практике
# уже ловили случай, когда правильный по сути ответ терялся только из-за
# одной лишней буквы перед двоеточием.
_ANSWER_LINE_RE = re.compile(r"^ОТВЕТ[А-ЯЁа-яё]{0,3}\s*:\s*(.*)$", re.IGNORECASE)
_CONTEXT_LINE_RE = re.compile(r"^КОНТЕКСТ[А-ЯЁа-яё]{0,3}\s*:\s*(.*)$", re.IGNORECASE)
_SEARCH_LINE_RE = re.compile(r"^ПОИСК[А-ЯЁа-яё]{0,3}\s*:\s*(.*)$", re.IGNORECASE)

# Живой случай, пойманный при массовом прогоне (batch_test.py): модель не
# перенесла "КОНТЕКСТ:" на отдельную строку, а дописала его В КОНЦЕ ТОЙ ЖЕ
# строки, что и ОТВЕТ ("...и т.д. 1) КОНТЕКСТ: -") — _CONTEXT_LINE_RE выше
# такое не ловит (требует начало строки), и весь хвост "КОНТЕКСТ: -" утекал
# прямо в подсказку пользователю. Этот regex — та же метка, но БЕЗ привязки
# к началу строки, ищем ВНУТРИ уже извлечённого текста ОТВЕТА как fallback.
_CONTEXT_INLINE_RE = re.compile(r"\s*КОНТЕКСТ[А-ЯЁа-яё]{0,3}\s*:\s*(.*)$", re.IGNORECASE)

# Ещё один вид порчи, пойманный на практике: модель пишет кириллическое слово
# "ОТВЕТ", но одна буква в нём — визуально НЕОТЛИЧИМАЯ латинская (например
# латинская "O" вместо кириллической "О" в самом начале). Глазами разницы
# нет, а точное регулярное выражение с кириллицей — не находит. Заменяем
# такие латинские буквы на кириллические ТОЛЬКО для поиска маркера — это
# посимвольная замена без изменения длины строки, так что все смещения
# совпадения остаются верными и для оригинального (незаменённого) текста,
# из которого мы реально достаём содержимое ответа.
_HOMOGLYPH_LATIN_TO_CYRILLIC = str.maketrans(
    "ABEKMHOPCTXabekmhopctx",
    "АВЕКМНОРСТХавекмнорстх",
)


def _delatinize(text: str) -> str:
    return text.translate(_HOMOGLYPH_LATIN_TO_CYRILLIC)


_BULLET_PREFIX_RE = re.compile(r"^[*•\-]\s*|^\d+[.)]\s*")


def _parse_hint(raw: str) -> tuple[str, str]:
    raw = raw.split(_STOP_MARKER, 1)[0]  # всё после маркера конца ответа не рассматриваем вообще
    found_answer_line = False
    reply, context = "", ""
    # Round 10j (см. проектный документ): раньше строки ПОСЛЕ "ОТВЕТ:"
    # собирались ТОЛЬКО когда сама строка "ОТВЕТ:" была пустой (см. комментарий
    # ниже про round 9/batch_test_followup.py). Живой баг, пойманный
    # пользователем на реальном звонке: вопрос "приведите примеры запроса"
    # (SQL) — модель написала "ОТВЕТ: Вот несколько примеров SQL запросов:",
    # а сами примеры — отдельными строками НИЖЕ. Раньше это ВСЁ терялось: raw
    # содержал полный текст с примерами, но извлекался только первый обрывок
    # фразы до конца строки — потому что reply уже был непустой ("Вот
    # несколько примеров...") и старое условие `collecting_empty_answer = not
    # reply` было ложным, дальнейшие строки вообще не собирались. Теперь
    # собираем строки-продолжения ВСЕГДА после "ОТВЕТ:" (до "КОНТЕКСТ:" или
    # конца), независимо от того, была ли сама строка "ОТВЕТ:" пустой —
    # различие только в том, КАК их потом склеивать обратно (см. ниже после
    # цикла).
    continuation_lines: list[str] = []
    collecting = False
    for line in raw.splitlines():
        line = line.strip()
        normalized = _delatinize(line)
        m = _ANSWER_LINE_RE.match(normalized)
        if m:
            found_answer_line = True
            reply = line[m.start(1) : m.end(1)].strip()
            collecting = True
            continuation_lines = []
            continue
        m = _CONTEXT_LINE_RE.match(normalized)
        if m:
            context = line[m.start(1) : m.end(1)].strip()
            collecting = False
            continue
        if collecting and line:
            continuation_lines.append(_BULLET_PREFIX_RE.sub("", line).strip())

    if not reply and continuation_lines:
        # Поймано на массовом прогоне batch_test_followup.py (см. обсуждение
        # в чате): на "Приведи пример для каждого из них" по спискам из
        # нескольких пунктов модель иногда выводит "ОТВЕТ:" пустой строкой-
        # лейблом, а сам содержательный ответ пишет ниже, часто списком через
        # "*" — раньше это полностью терялось (см. ветку "elif not reply"
        # ниже и её диагностический print, который это и поймал: строка была
        # непустой, просто на следующих строках). Склеиваем такие строки в
        # обычный текст ответа, срезая маркеры списка ("*", "-", "1)"), чтобы
        # не тащить их в подсказку как есть. Поведение не изменилось по
        # сравнению с тем, что было до round 10j — только имя переменной.
        reply = "; ".join(continuation_lines)
    elif reply and reply != "-" and continuation_lines:
        # Round 10j, новая ветка: "ОТВЕТ:" НЕ пустая (короткое вступление
        # вроде "Вот несколько примеров:"), а содержательная часть — строками
        # НИЖЕ. Раньше это отбрасывалось целиком (см. живой баг в докстринге
        # функции выше) — теперь дописываем через перенос строки, а не "; "
        # как в ветке выше: список запросов/кода через "; " превратился бы в
        # нечитаемую кашу, построчный вид тут важнее. `reply != "-"` —
        # защита сентинела МУСОР (см. `if reply == "-":` ниже): если модель
        # почему-то дописала что-то после "ОТВЕТ: -", не хотим случайно
        # испортить проверку на мусор склейкой.
        reply = reply + "\n" + "\n".join(continuation_lines)

    # Fallback на случай, если "КОНТЕКСТ:" не оказался на отдельной строке
    # (см. комментарий у _CONTEXT_INLINE_RE) — ищем его уже ВНУТРИ текста
    # reply и отрезаем оттуда, а не отдаём как есть пользователю. _delatinize
    # — посимвольная замена без изменения длины строки, так что смещения
    # совпадения (m.start/m.end) остаются верными и для оригинального
    # (незаменённого) reply.
    if not context:
        normalized_reply = _delatinize(reply)
        m = _CONTEXT_INLINE_RE.search(normalized_reply)
        if m:
            context = reply[m.start(1) : m.end(1)].strip()
            reply = reply[: m.start(0)].strip()

    reply = _clean_field(reply)
    context = _clean_field(context)
    if context == "-":
        context = ""
    if reply == "-":
        # Модель явно сказала "отвечать не на что" (см. правило в промпте про
        # реплики без вопроса/просьбы) — обычно это осознанно, но иногда
        # модель ошибочно принимает за "нет вопроса" настоящий вопрос
        # (баг, который уже ловили на практике). Печатаем сырой ответ, чтобы
        # это было видно в консоли и можно было отличить одно от другого —
        # сам вопрос из транскрипта виден чуть выше (его печатает
        # transcript_store при получении фразы).
        snippet = raw.strip().replace("\n", " ⏎ ")[:200]
        print(f"[hints] модель посчитала, что в реплике нет вопроса, сырой ответ: {snippet!r}")
        reply = ""
    elif not found_answer_line:
        # ВАЖНОЕ отличие от строки выше: тут модель вообще не вывела строку
        # "ОТВЕТ:" в ожидаемом формате — например истратила лимит токенов на
        # скрытые рассуждения (если модель "думающая" и режим размышлений не
        # выключился как надо) и не успела дойти до самого ответа. Внешне это
        # выглядит так же, как "нет вопроса" (пустая подсказка), но причина
        # другая — печатаем сырой ответ модели, чтобы это было видно в
        # консоли, а не терялось молча.
        snippet = raw.strip().replace("\n", " ⏎ ")[:200]
        print(f"[hints] модель не вывела строку ОТВЕТ: в ожидаемом формате, сырой ответ: {snippet!r}")
        # На практике содержимое в таком случае часто всё равно нормальный,
        # честный ответ по существу — модель забыла сам лейбл "ОТВЕТ:" (не
        # ответила чем-то бессмысленным), особенно на разросшемся промпте,
        # где мелкой модели сложнее держать формат идеально. Выбрасывать
        # полностью годный ответ только из-за отсутствия лейбла — обидная
        # потеря.
        #
        # Round 10k (см. проектный документ) — живой баг с реального звонка:
        # порог "не больше пары строк" (было `line_count <= 2`) оказался
        # ГОРАЗДО строже, чем нужно, и молча дропал ЧЕТЫРЕ подряд честных
        # ответа за один звонок — все они были нормальными многострочными
        # примерами SQL-запросов с JOIN (вступление + ```код``` на несколько
        # строк + короткое пояснение), которые GigaChat написала БЕЗ лейбла
        # "ОТВЕТ:" вообще (не редкий случай — так происходит на КАЖДЫЙ запрос
        # "приведи пример" без явного вопроса перед этим). Условие "≤2
        # строки" никогда не пропустило бы такой ответ, даже полностью
        # нормальный, просто по факту, что код на нескольких строках —
        # это ожидаемый, а не патологический случай для этого ассистента
        # (он для QA/разработчиков, где примеры кода — обычное дело).
        #
        # Линия-в-линию количество строк вообще плохо отличает "утекшие
        # рассуждения" от "нормального многострочного примера" — оба могут
        # быть длинными, а короткая одна строка тоже может быть мусором.
        # Настоящая защита от степени "убежавшая" генерация уже есть в
        # _clean_field() (лимит по ДЛИНЕ _MAX_FIELD_LEN=8192 символов, round
        # 11 — раньше было 2200, см. докстринг у _MAX_FIELD_LEN — и обрыв
        # по CJK-побегу) — те же проверки, что используются для ЛЮБОГО поля
        # в этой функции, а не отдельная, более узкая проверка только для
        # этой ветки. Оставляем щедрый потолок по строкам (40) как ещё один,
        # более грубый рубеж на случай совсем уж экстремального обвала (не
        # убираем целиком, чтобы не остаться совсем без защиты) — вместе с
        # length-капом в _clean_field этого достаточно, чтобы отсечь
        # реальный мусор, но пропустить любой честный пример кода.
        stripped_raw = raw.strip()
        line_count = len(stripped_raw.splitlines())
        looks_like_search = bool(_SEARCH_LINE_RE.match(_delatinize(stripped_raw)))
        if stripped_raw and line_count <= 40 and not looks_like_search:
            candidate = _clean_field(raw)
            if candidate and candidate != "-":
                reply = candidate
                print(f"[hints] использую сырой текст как ответ без лейбла ОТВЕТ:: {candidate!r}")
    elif not reply:
        # Третий отдельный случай: строка "ОТВЕТ:" есть, это не "-", но после
        # двоеточия буквально пусто — модель начала отвечать по формату и
        # ничего не написала. Ни один из двух случаев выше это не ловит,
        # раз нашли на практике — логируем и это.
        snippet = raw.strip().replace("\n", " ⏎ ")[:200]
        print(f"[hints] модель вывела ОТВЕТ:, но оставила его пустым, сырой ответ: {snippet!r}")
    return reply, context


def _parse_hint_partial(raw: str) -> tuple[str, str]:
    """
    Облегчённая версия _parse_hint() — специально для ЖИВОГО предпросмотра
    во время стриминга (см. _call_ollama_stream), пока raw ещё растёт по
    мере поступления кусочков от Ollama. Разбирает те же метки ОТВЕТ:/
    КОНТЕКСТ: и так же подхватывает строки-продолжения после пустого
    "ОТВЕТ:" (см. _BULLET_PREFIX_RE), но НЕ применяет эвристики, рассчитанные
    на уже ПОЛНОСТЬЮ полученный текст:
      - не трактует "ОТВЕТ: -" как осознанный отказ (на неполном тексте
        нельзя быть уверенным, что дефис — это весь ответ, а не начало
        обычного предложения или маркера списка);
      - не включает fallback "лейбла ОТВЕТ: вообще нет, берём сырой текст
        как есть" — на растущем тексте это может на долю секунды показать
        мусор ("ПОИСК: ...") как будто это уже готовый ответ;
      - не режет через _clean_field (CJK-обрыв, лимит длины) — эти проверки
        имеют смысл только на окончательном тексте.
    Итоговый, надёжный результат всё равно даёт _parse_hint() на полностью
    полученном raw — эта функция только предварительный, "на глаз" разбор
    ради живого ощущения печати в оверлее, никогда не подменяет финальный.
    """
    reply, context = "", ""
    collecting = False
    continuation: list[str] = []
    for line in raw.split(_STOP_MARKER, 1)[0].splitlines():
        line = line.strip()
        normalized = _delatinize(line)
        m = _ANSWER_LINE_RE.match(normalized)
        if m:
            reply = line[m.start(1) : m.end(1)].strip()
            collecting = not reply
            continuation = []
            continue
        m = _CONTEXT_LINE_RE.match(normalized)
        if m:
            context = line[m.start(1) : m.end(1)].strip()
            collecting = False
            continue
        if collecting and line:
            continuation.append(_BULLET_PREFIX_RE.sub("", line).strip())
    if not reply and continuation:
        reply = "; ".join(continuation)
    if reply == "-":
        reply = ""
    return reply, context


def _split_current_line(recent_transcript: str) -> tuple[str, str]:
    """
    Разбивает хвост транскрипта на "Историю разговора" (всё, кроме последней
    строки) и "ТЕКУЩУЮ ФРАЗУ" (последняя непустая строка). Раньше модель
    получала это одним сплошным текстом и должна была САМА догадаться, что
    отвечать нужно только на последнюю строку — расчёт на то, что она
    правильно поймёт неявный порядковый номер в сплошном тексте, оказался
    ненадёжным (на практике модель то и дело "залипала" на более раннем, более
    "интересном" вопросе). Явное разделение на два подписанных блока — гораздо
    более сильный сигнал, чем описательная инструкция.
    """
    lines = [ln for ln in recent_transcript.splitlines() if ln.strip()]
    if not lines:
        return "", ""
    return "\n".join(lines[:-1]), lines[-1]


def _build_user_message(
    recent_transcript: str,
    search_block: str = "",
    pending_clarification: str | None = None,
    kb_block: str = "",
    own_answers: list[str] | None = None,
    extra_context: str | None = None,
    retrieved_context: str | None = None,
    known_topics_block: str = "",
) -> str:
    # known_topics_block (round 10, рычаг 2 — см. _format_known_topics/
    # _TOPIC_MEMORY_RULES выше) — по умолчанию пустая строка, так что ни один
    # из существующих вызовов этой функции (generate_hint/generate_hint_gigachat
    # и все batch_test_*.py) её не передаёт и не видит вообще никакой разницы.
    history, current_line = _split_current_line(recent_transcript)
    history_block = f"История разговора:\n{history}\n\n" if history else ""
    # retrieved_context (см. judge.py + main.py/hint_worker) — кусок БОЛЕЕ
    # СТАРОЙ истории, не попавший в окно последних HINTS_CONTEXT_LINES строк
    # выше (history), но к которому текущая фраза явно отсылает (судья
    # определил это по continues_tags). Это ДОПОЛНЕНИЕ к history, а не замена
    # — окно последних строк и теговый retrieval решают разные задачи и не
    # конфликтуют (см. проектный документ). Ставим сразу после history_block
    # — по смыслу это тоже "то, что было сказано", просто раньше по времени.
    retrieved_block = f"{retrieved_context}\n\n" if retrieved_context else ""
    # "История разговора" — это только то, что было СКАЗАНО ВСЛУХ (транскрипт
    # речи). Наши же собственные прошлые ОТВЕТЫ туда не попадают — они не
    # произносятся вслух (это текст в оверлее), поэтому без этого отдельного
    # блока модель физически не может знать, что она сама только что ответила
    # на предыдущий вопрос. На практике это ломало ровно то правило про
    # "просьбу продолжить тему предыдущего ОТВЕТА" (см. _CORE_RULES) — модель
    # честно пыталась его выполнить, но у неё просто не было данных, и она
    # вместо этого выдумывала правдоподобную, но другую подмену (поймали
    # случай: правильный ответ был "конфиденциальность, целостность,
    # доступность", а на "расскажи о каждом из них" модель заново придумала
    # другую тройку принципов "полнота, точность, эффективность").
    own_answers_block = ""
    if own_answers:
        numbered = "\n".join(f"{i}. {a}" for i, a in enumerate(own_answers, 1))
        own_answers_block = (
            "Твои недавние ответы в этом разговоре (от старых к новым — это факты, "
            "которые ты САМ только что озвучил, а не то, что сказал собеседник). Если "
            "текущая фраза просит продолжить/раскрыть/уточнить/перечислить подробнее "
            "то, что ты уже назвал — бери именно ЭТИ факты (особенно последний по "
            "списку пункт), а не придумывай новый список с нуля:\n"
            f"{numbered}\n\n"
        )
    pending_block = (
        f'Твой предыдущий уточняющий вопрос: "{pending_clarification}"\n\n' if pending_clarification else ""
    )
    kb_section = f"База знаний (см. правила выше про её использование):\n{kb_block}\n\n" if kb_block else ""
    # extra_context (см. HINTS_EXTRA_CONTEXT в .env, настройка Settings) —
    # свободный текст от пользователя про сам разговор, который
    # не меняется от вопроса к вопросу и потому не идёт через "Историю
    # разговора" (та — только реально произнесённая речь). Придумано из-за
    # конкретного случая: GigaChat, отвечая на вопрос "напиши функцию для
    # проверки палиндрома" (без указания языка), один раз выдала код на
    # C/C++ вместо ожидаемого Python — модели попросту неоткуда было знать,
    # какой язык вообще имеется в виду. Этот блок — способ сообщить такие
    # вещи один раз (язык программирования по умолчанию, стек, позиция и
    # т.п.), а не при каждом отдельном вопросе.
    context_block = f"Контекст этого разговора (учитывай во всех ответах):\n{extra_context}\n\n" if extra_context else ""
    return (
        f"{context_block}"
        f"{known_topics_block}"
        f"{history_block}"
        f"{retrieved_block}"
        f"{own_answers_block}"
        f"{pending_block}"
        f"{kb_section}"
        f"ТЕКУЩАЯ ФРАЗА (отвечай СТРОГО и ТОЛЬКО на неё):\n{current_line}{search_block}\n\n"
        "Ответь по инструкции выше.\n/no_think"
    )


def _parse_search_request(raw: str) -> str | None:
    """
    Первый проход мог попросить поиск вместо ответа — распознаём это. Если в
    ответе почему-то есть И "ПОИСК:", И "ОТВЕТ:" одновременно — считаем, что
    модель всё же ответила (это уже полноценный ответ), поиск не запрашиваем.
    Как и в _parse_hint, ищем через _delatinize — та же защита от латинской
    буквы-двойника вместо кириллической в начале маркера.
    """
    raw = raw.split(_STOP_MARKER, 1)[0]
    search_query: str | None = None
    for line in raw.splitlines():
        line = line.strip()
        normalized = _delatinize(line)
        if _ANSWER_LINE_RE.match(normalized):
            return None  # модель уже дала полноценный ответ — поиск не нужен
        if search_query is None:
            m = _SEARCH_LINE_RE.match(normalized)
            if m:
                query = line[m.start(1) : m.end(1)].strip().strip('"')
                # Та же порча, что и в ОТВЕТ/КОНТЕКСТ (обвал в китайский,
                # слипшееся кириллица+латиница слово) может случиться и тут —
                # раньше query шёл в search_web() и в лог как есть, без
                # _clean_field. На практике поймали и полный китайский обвал
                # ('для каких целей в飞机尾翼上的孔洞有何作用？'), и слипшиеся
                # слова ('памятник сphinx ru', 'лорд-kanцлер') — всё это
                # долетало прямо до поисковика. Прогоняем через ту же чистку.
                query = _clean_field(query)
                if query and query != "-":
                    search_query = query
    return search_query


def _call_ollama(
    system_prompt: str,
    user_message: str,
    model: str,
    host: str,
    timeout: float,
    session: requests.Session,
    num_ctx: int | None = None,
) -> str:
    response = session.post(
        f"{host.rstrip('/')}/api/chat",
        json={
            "model": model,
            "messages": [
                {"role": "system", "content": system_prompt},
                {"role": "user", "content": user_message},
            ],
            "stream": False,
            # На случай если модель — из "думающих" (Qwen3 и т.п.): без этого
            # она перед ответом ещё генерирует скрытые рассуждения, это лишние
            # секунды задержки, которые нам тут не нужны. Для моделей без
            # режима размышлений (как нынешняя qwen2.5) поле просто игнорируется.
            "think": False,
            "options": {
                # Раньше было 180, потом 300 — оба раза поднимали по тому же
                # живому симптому: жёсткий обрыв многопунктового перечисления
                # на середине, без строки КОНТЕКСТ: (то есть это не осознанная
                # остановка модели, а именно упор в num_predict). 300 хватало
                # для qwen2.5:7b (см. историю правок выше), но на живом
                # звонке с gemma2:9b (реальная модель в .env пользователя)
                # поймали новый случай: вопрос "расскажи про каждый уровень"
                # после верного списка "7 уровней модели OSI" оборвался уже
                # на 3-м уровне из 7, прямо посреди слова. gemma2 в этой
                # задаче тратит на кириллицу заметно больше токенов на тот же
                # печатный текст, чем qwen2.5, поэтому тот же лимит режет её
                # ощутимо раньше. Сначала подняли до 700 (с запасом), но
                # решили не мелочиться и сразу взять с большим запасом — 1500.
                # Цена этого почти нулевая: короткие и средние ответы всё
                # равно останавливаются по стоп-маркеру "###" сильно раньше
                # потолка, им лишний запас вообще не виден. Единственный
                # реальный (и редкий) сценарий, где цена не нулевая — если
                # генерация когда-нибудь "убежит" и ни разу не допишет "###"
                # (зависание/повтор) — тогда декодирование, будучи строго
                # последовательным, будет идти до этого потолка, и каждый
                # лишний токен — это лишние реальные миллисекунды ожидания
                # именно в этом сбойном случае. Сознательно жертвуем этим
                # ради того, чтобы честные многопунктовые ответы больше не
                # обрывались на полуслове (см. _MAX_FIELD_LEN — тот же потолок
                # держим и там, чтобы не получить новое узкое место вместо
                # старого).
                "num_predict": 1500,
                # 0 = жадное декодирование, минимум случайности: на каждом шаге
                # берём самый вероятный токен, без "броска кубика". Мы всё
                # равно генерируем только одну попытку на вопрос (не выбираем
                # лучшую из нескольких) — значит самый вероятный вариант и
                # есть самая надёжная ставка. Заодно один и тот же входной
                # текст теперь должен давать один и тот же ответ что в
                # test_hint.py, что в реальном звонке.
                "temperature": 0.0,
                "repeat_penalty": 1.3,  # сбивает склонность мелких моделей повторять вход
                "stop": [_STOP_MARKER],  # физически обрывает генерацию на маркере конца ответа
                **({"num_ctx": num_ctx} if num_ctx is not None else {}),
                # ^ Размер контекстного окна — меньше окно, меньше VRAM под
                # KV-кэш модели. На видеокарте, где модель впритык не влезает
                # целиком (см. историю про 8ГБ и gemma2:9b: на дефолтных 4096
                # токенах контекста 20% модели уходило на CPU, что резко
                # замедляло и местами роняло генерацию в таймаут; на 2048 —
                # влезла на 100% GPU). Если не передан явно — используем
                # дефолт самой модели (ничего не меняется в поведении).
            },
            # Без этого Ollama выгружает модель из VRAM после ~5 минут простоя
            # (см. комментарий в warmup_model) — если между вопросами в звонке
            # была пауза больше этого, СЛЕДУЮЩИЙ запрос сначала долго грузит
            # модель заново с диска, и это выглядит как "внезапно стало очень
            # медленно". Держим модель загруженной весь звонок.
            "keep_alive": "30m",
        },
        timeout=timeout,
    )
    response.raise_for_status()
    return response.json()["message"]["content"]


def _call_ollama_stream(
    system_prompt: str,
    user_message: str,
    model: str,
    host: str,
    timeout: float,
    session: requests.Session,
    on_chunk: Callable[[str], None] | None = None,
    num_ctx: int | None = None,
) -> str:
    """
    Потоковая версия _call_ollama() — та же самая настройка запроса (стоп-
    маркер, num_predict, temperature=0 и т.д.), но с "stream": True: Ollama
    отдаёт ответ не одним блоком в конце, а построчно, отдельным JSON-
    объектом на каждый новый кусочек текста (обычно несколько токенов за
    раз, не по одному символу). on_chunk (опционально) вызывается после
    КАЖДОГО полученного кусочка с уже НАКОПЛЕННЫМ текстом целиком (не
    дельтой) — так его можно сразу отдать в _parse_hint_partial(), не храня
    состояние снаружи. Нужно исключительно для "живого" предпросмотра в
    оверлее (см. main.py/overlay.py) — надёжный финальный текст по-прежнему
    возвращается целиком, как и раньше, и разбирается через _parse_hint().
    """
    response = session.post(
        f"{host.rstrip('/')}/api/chat",
        json={
            "model": model,
            "messages": [
                {"role": "system", "content": system_prompt},
                {"role": "user", "content": user_message},
            ],
            "stream": True,
            "think": False,
            "options": {
                "num_predict": 1500,  # см. подробный комментарий у этого же параметра в _call_ollama
                "temperature": 0.0,
                "repeat_penalty": 1.3,
                "stop": [_STOP_MARKER],
                **({"num_ctx": num_ctx} if num_ctx is not None else {}),  # см. комментарий в _call_ollama
            },
            "keep_alive": "30m",
        },
        timeout=timeout,
        stream=True,
    )
    response.raise_for_status()
    pieces: list[str] = []
    for line in response.iter_lines():
        if not line:
            continue
        # Одна строка — один JSON-объект вида {"message": {"content": "..."},
        # "done": false}, финальная строка несёт "done": true (в ней тоже
        # может быть непустой content — не пропускаем её просто по done).
        chunk = json.loads(line)
        delta = chunk.get("message", {}).get("content", "")
        if delta:
            pieces.append(delta)
            if on_chunk is not None:
                on_chunk("".join(pieces))
        if chunk.get("done"):
            break
    return "".join(pieces)


def _call_ollama_retrying(
    system_prompt: str,
    user_message: str,
    model: str,
    host: str,
    timeout: float,
    session: requests.Session,
    on_partial: Callable[[str, str], None] | None = None,
    num_ctx: int | None = None,
) -> str:
    """
    На практике (первый же реальный вопрос звонка, сразу после успешного
    прогрева) поймали случай, когда Ollama отвечает HTTP 200, но
    message.content — буквально пустая строка, без единого токена. Это не
    та же история, что "ОТВЕТ: -" (модель осознанно решила, что вопроса
    нет) и не обрыв соединения (он бы поднял исключение раньше) — модель в
    этом случае просто ничего не сгенерировала. Причина пока не понятна
    (не похоже на баг разбора текста — тут разбирать нечего), похоже на
    какой-то разовый сбой генерации именно на холодном старте модели.
    Раз с temperature=0 повтор того же запроса не гарантированно повторит
    ту же пустоту (если дело в состоянии модели/раннера, а не в промпте) —
    тихо повторяем запрос несколько раз, прежде чем сдаваться и показывать
    пользователю, что подсказки не будет. Раньше был только один повтор
    (2 попытки всего) — на практике поймали случай, когда пустым оказался
    даже он, и живой, законный вопрос ("подробнее, что каждое значит")
    остался вообще без подсказки. Каждая лишняя попытка — это лишние секунды
    задержки ТОЛЬКО в этом редком случае (обычный успешный ответ проходит с
    первого раза, как и раньше), так что расширить именно этот путь дёшево.

    on_partial (опционально): если передан — используем СТРИМИНГ (см.
    _call_ollama_stream) и после каждого кусочка вызываем on_partial с уже
    разобранными _parse_hint_partial() (reply, context) — специально для
    живого "печатает…" эффекта в оверлее. Без on_partial поведение и путь
    полностью совпадают со старым (нестриминговый _call_ollama) — так
    batch_test*.py и любой другой вызывающий код, не передающий on_partial,
    не затрагивается этим изменением вообще.
    """
    max_attempts = 3
    raw = ""
    for attempt in range(1, max_attempts + 1):
        if on_partial is not None and attempt > 1:
            # Предыдущая попытка была пустой — сбрасываем то, что успело
            # (в теории) промелькнуть в предпросмотре, прежде чем начинать
            # заново, чтобы не оставить в оверлее огрызок от неудачной попытки.
            on_partial("", "")
        if on_partial is not None:
            raw = _call_ollama_stream(
                system_prompt,
                user_message,
                model,
                host,
                timeout=timeout,
                session=session,
                on_chunk=lambda acc: on_partial(*_parse_hint_partial(acc)),
                num_ctx=num_ctx,
            )
        else:
            raw = _call_ollama(
                system_prompt, user_message, model, host, timeout=timeout, session=session, num_ctx=num_ctx
            )
        if raw.strip():
            return raw
        if attempt < max_attempts:
            print(f"[hints] модель вернула пустой ответ (0 токенов, попытка {attempt}/{max_attempts}) — пробую ещё раз")
    return raw


def warmup_model(
    model: str = "qwen2.5:7b",
    host: str = "http://localhost:11434",
    timeout: float = 120.0,
    num_ctx: int | None = None,
) -> None:
    """
    Ollama выгружает модель из видеопамяти, если её не трогали ~5 минут
    (настройка keep_alive) — тогда первый реальный запрос вынужден сначала
    ждать загрузки модели с диска в VRAM, и это легко может не уложиться в
    обычный тайм-аут подсказки (были случаи read timeout прямо на первом
    вопросе звонка). Поэтому дёргаем Ollama один раз заранее, до начала
    звонка, специально с большим тайм-аутом — чтобы к первому реальному
    вопросу модель была уже прогрета и следующий ответ пришёл быстро.

    num_ctx ОБЯЗАТЕЛЬНО должен совпадать с тем, что передаётся в generate_hint()
    ниже по звонку — размер контекста задаётся один раз при ЗАГРУЗКЕ модели
    в VRAM, и если тут прогреть с одним значением, а потом запросить с
    другим, Ollama тихо перезагрузит модель на первом же реальном вопросе
    звонка — и весь смысл прогрева (быстрый первый ответ) пропадёт.
    """
    try:
        response = requests.post(
            f"{host.rstrip('/')}/api/chat",
            json={
                "model": model,
                "messages": [{"role": "user", "content": "привет"}],
                "stream": False,
                "options": {
                    "num_predict": 1,
                    **({"num_ctx": num_ctx} if num_ctx is not None else {}),
                },
                "keep_alive": "30m",  # см. комментарий в _call_ollama — та же причина
            },
            timeout=timeout,
        )
        # Без этой проверки, например, 404 (модели с таким именем просто нет
        # в Ollama) молча "проходил" бы как будто прогрев удался — а ошибка
        # вылезала бы только на первом реальном вопросе в звонке, что и
        # произошло на практике и сбило с толку. Проверяем сразу и громко.
        response.raise_for_status()
    except Exception as e:
        print(
            f"[hints] НЕ УДАЛОСЬ прогреть модель '{model}' ({e}) — "
            "похоже, её нет в Ollama под этим именем. Проверьте `ollama list` "
            "и сверьте с OLLAMA_MODEL в .env. Подсказки работать не будут."
        )


def generate_hint(
    recent_transcript: str,
    model: str = "qwen2.5:7b",
    host: str = "http://localhost:11434",
    timeout: float = 30.0,
    enable_search: bool = True,
    num_ctx: int | None = None,
    session_box: dict | None = None,
    pending_clarification: str | None = None,
    kb_enabled: bool = False,
    kb_path: str | None = None,
    kb_top_k: int = 3,
    kb_min_score: float = 0.15,
    own_answers: list[str] | None = None,
    on_partial: Callable[[str, str], None] | None = None,
    extra_context: str | None = None,
    retrieved_context: str | None = None,
) -> tuple[str, str]:
    """
    session_box (опционально): {"session": requests.Session|None, "lock": threading.Lock}.
    Пока этот вызов работает, актуальная сессия лежит в session_box["session"] —
    вызывающий код (main.py) может в любой момент из другого потока вызвать
    session.close(), если пришёл более новый вопрос и этот ответ уже не нужен.
    Закрытая на середине запроса сессия обрывает сетевое соединение — Ollama
    получает разрыв и прекращает генерацию, а requests тут же поднимает
    исключение вместо того, чтобы тихо ждать до конца.

    pending_clarification (опционально): текст ПРЕДЫДУЩЕЙ подсказки, если она
    была уточняющим вопросом от нас самих (main.py решает это по "?" на конце
    и передаёт сюда) — тогда модель знает, что текущая фраза, возможно,
    отвечает именно на этот вопрос, и должна наконец дать содержательный
    ответ, а не снова уточнять или молчать из-за "нет вопроса".

    kb_enabled/kb_path/kb_top_k/kb_min_score (опционально): локальная база
    знаний (см. knowledge_base.py) — заранее подготовленный пользователем
    набор пар вопрос/ответ (например, справочник по продукту). Если включена,
    ПЕРЕД первым запросом к модели по ТЕКУЩЕЙ ФРАЗЕ ищутся похожие записи
    (простое сравнение по словам, без embeddings) и, если что-то нашлось
    выше kb_min_score, добавляются в промпт отдельным блоком "База знаний" —
    в отличие от веб-поиска это не требует второго похода к модели, поиск
    по базе знаний быстрый и синхронный, делается сразу в первом проходе.

    own_answers (опционально): последние несколько ОТВЕТОВ, которые мы сами уже
    показали пользователю в этом же разговоре (main.py копит их отдельно —
    "История разговора" содержит только распознанную речь, наши собственные
    ответы туда не попадают, см. комментарий в _build_user_message). Нужно,
    чтобы просьбы "расскажи подробнее / о каждом из них / продолжи" могли
    опираться на то, что мы уже реально сказали, а не выдумывать заново.

    extra_context (опционально): свободный текст от пользователя про сам
    разговор (например, "Язык программирования по умолчанию —
    Python."), который не меняется от вопроса к вопросу — см. HINTS_EXTRA_CONTEXT
    в .env и комментарий в _build_user_message.

    retrieved_context (опционально): готовый текстовый блок "возврат к теме"
    (main.py/hint_worker собирает его по JudgeVerdict.continues_tags ДО вызова
    этой функции — см. judge.py и проектный документ). Просто пробрасывается
    в _build_user_message(), сюда попадает уже полностью сформированным.

    on_partial (опционально): передаётся насквозь в _call_ollama_retrying —
    см. её докстринг. Если поиск (ПОИСК:) вообще не потребовался (KB нашла
    ответ или модель сразу ответила по FINAL_PROMPT) — партиалы приходят
    только с единственного прохода. Если потребовался — партиалы приходят
    сначала с ПЕРВОГО прохода тоже, но там модель отвечает "ПОИСК: ..." (не
    "ОТВЕТ:"), так что _parse_hint_partial на нём стабильно возвращает
    ("", "") — никакого "мусора" в предпросмотре в момент решения об
    обращении к поиску не появится, живой текст пойдёт только со второго,
    финального прохода.
    """
    session = requests.Session()
    if session_box is not None:
        with session_box["lock"]:
            session_box["session"] = session

    try:
        kb_block = ""
        if kb_enabled and kb_path:
            try:
                kb = _get_kb(kb_path)
                _, current_line = _split_current_line(recent_transcript)
                # Убираем метку говорящего ("Собеседник: "/"Я: ") перед
                # поиском — см. _SPEAKER_LABEL_RE. Иначе слово "собеседник"
                # само попадает в запрос и занижает score любого совпадения.
                kb_query = _SPEAKER_LABEL_RE.sub("", current_line, count=1)
                # См. _CONTINUATION_KB_MIN_SCORE — на вопросе-продолжении
                # (own_answers непустой) поднимаем порог совпадения, чтобы
                # случайное пересечение по общим словам не подсовывало
                # модели не связанный с разговором факт вместо own_answers.
                effective_min_score = kb_min_score
                if own_answers:
                    effective_min_score = max(kb_min_score, _CONTINUATION_KB_MIN_SCORE)
                kb_matches = search_kb(kb_query, kb, top_k=kb_top_k, min_score=effective_min_score)
                kb_block = format_kb_for_prompt(kb_matches)
            except Exception as e:
                print(f"[kb] поиск по базе знаний не удался: {e}")

        # "/no_think" в конце сообщения — жёсткое текстовое отключение режима
        # рассуждений у Qwen3 (работает через шаблон чата модели, независимо
        # от того, поддерживает ли конкретная версия Ollama JSON-параметр
        # "think" из _call_ollama). Для моделей без такого режима (qwen2.5 и
        # т.п.) это просто игнорируется как незначащий хвост текста.
        user_message = _build_user_message(
            recent_transcript,
            pending_clarification=pending_clarification,
            kb_block=kb_block,
            own_answers=own_answers,
            extra_context=extra_context,
            retrieved_context=retrieved_context,
        )

        # Если база знаний уже нашла подходящую запись — поиск в принципе не
        # нужен (см. правило в _CORE_RULES про приоритет базы знаний). На
        # практике поймали случай, когда модель всё равно просила ПОИСК:,
        # хотя kb_block содержал практически дословное совпадение — с малой
        # моделью и разросшимся промптом полагаться только на то, что она
        # сама всегда правильно применит это правило, ненадёжно. Поэтому
        # закрываем это на уровне кода: раз KB что-то нашла, вариант
        # "попросить поиск" физически не предлагается (используем FINAL_PROMPT
        # напрямую) — заодно на такой вопрос уходит один проход вместо двух,
        # то есть и быстрее.
        effective_enable_search = enable_search and not kb_block
        prompt = FIRST_PASS_PROMPT if effective_enable_search else FINAL_PROMPT

        raw = _call_ollama_retrying(
            prompt, user_message, model, host, timeout=timeout, session=session, on_partial=on_partial, num_ctx=num_ctx
        )

        if effective_enable_search:
            query = _parse_search_request(raw)
            if query:
                print(f"[hints] ищу в интернете: {query!r}")
                results = search_web(query)
                snippet_text = format_results_for_prompt(results)
                search_block = (
                    f"\n\nРезультаты поиска в интернете по запросу «{query}» "
                    f"(проверенные актуальные факты):\n{snippet_text}"
                    if snippet_text
                    else ""
                )
                user_message2 = _build_user_message(
                    recent_transcript,
                    search_block=search_block,
                    pending_clarification=pending_clarification,
                    kb_block=kb_block,
                    own_answers=own_answers,
                    extra_context=extra_context,
                    retrieved_context=retrieved_context,
                )
                raw = _call_ollama_retrying(
                    FINAL_PROMPT,
                    user_message2,
                    model,
                    host,
                    timeout=timeout,
                    session=session,
                    on_partial=on_partial,
                    num_ctx=num_ctx,
                )

        return _parse_hint(raw)
    finally:
        if session_box is not None:
            with session_box["lock"]:
                if session_box.get("session") is session:
                    session_box["session"] = None
        session.close()


def generate_hint_gigachat(
    recent_transcript: str,
    credentials: str,
    model: str,
    ca_bundle_file: str | None = None,
    timeout: float = 60.0,
    enable_search: bool = True,
    pending_clarification: str | None = None,
    kb_enabled: bool = False,
    kb_path: str | None = None,
    kb_top_k: int = 3,
    kb_min_score: float = 0.15,
    own_answers: list[str] | None = None,
    on_partial: Callable[[str, str], None] | None = None,
    extra_context: str | None = None,
    retrieved_context: str | None = None,
) -> tuple[str, str]:
    """
    То же самое, что generate_hint() — та же логика (база знаний -> первый
    проход -> при необходимости веб-поиск -> финальный проход -> тот же
    _parse_hint), только вместо _call_ollama_retrying дёргается облачная
    GigaChat через call_gigachat_retrying (см. llm_gigachat.py). Специально
    НЕ переделываем generate_hint() под общий "бэкенд" параметр — это отдельная,
    самостоятельная функция, чтобы ни одна правка тут не могла случайно
    задеть уже отлаженный и проверенный на реальных звонках путь через Ollama.

    Таймаут по умолчанию заметно больше, чем у generate_hint() (60с против
    обычных ~30с) — GigaChat это сеть (а не локальная видеокарта), и
    осознанно допускаем дополнительную задержку именно на сложных вопросах
    (см. main.py, _looks_like_hard_question) ради заметно более качественного
    рассуждения на задачах по программированию и решаемых ситуационных
    вопросах, где у 7B-модели на 8ГБ видеокарте банально не хватает "ума".

    Параметры и их смысл — см. докстринг generate_hint(), совпадают один в один.
    """
    kb_block = ""
    if kb_enabled and kb_path:
        try:
            kb = _get_kb(kb_path)
            _, current_line = _split_current_line(recent_transcript)
            kb_query = _SPEAKER_LABEL_RE.sub("", current_line, count=1)
            effective_min_score = kb_min_score
            if own_answers:
                effective_min_score = max(kb_min_score, _CONTINUATION_KB_MIN_SCORE)
            kb_matches = search_kb(kb_query, kb, top_k=kb_top_k, min_score=effective_min_score)
            kb_block = format_kb_for_prompt(kb_matches)
            _log_kb_matches(kb_query, kb_matches, effective_min_score)
        except Exception as e:
            print(f"[kb] поиск по базе знаний не удался: {e}")

    user_message = _build_user_message(
        recent_transcript,
        pending_clarification=pending_clarification,
        kb_block=kb_block,
        own_answers=own_answers,
        extra_context=extra_context,
        retrieved_context=retrieved_context,
    )

    effective_enable_search = enable_search and not kb_block
    prompt = FIRST_PASS_PROMPT if effective_enable_search else FINAL_PROMPT

    on_chunk = (lambda acc: on_partial(*_parse_hint_partial(acc))) if on_partial is not None else None
    raw = call_gigachat_retrying(
        prompt, user_message, model, credentials, ca_bundle_file, timeout=timeout, on_chunk=on_chunk
    )

    if effective_enable_search:
        query = _parse_search_request(raw)
        if query:
            print(f"[hints:gigachat] ищу в интернете: {query!r}")
            results = search_web(query)
            snippet_text = format_results_for_prompt(results)
            search_block = (
                f"\n\nРезультаты поиска в интернете по запросу «{query}» "
                f"(проверенные актуальные факты):\n{snippet_text}"
                if snippet_text
                else ""
            )
            user_message2 = _build_user_message(
                recent_transcript,
                search_block=search_block,
                pending_clarification=pending_clarification,
                kb_block=kb_block,
                own_answers=own_answers,
                extra_context=extra_context,
                retrieved_context=retrieved_context,
            )
            raw = call_gigachat_retrying(
                FINAL_PROMPT, user_message2, model, credentials, ca_bundle_file, timeout=timeout, on_chunk=on_chunk
            )

    return _parse_hint(raw)



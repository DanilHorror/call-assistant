"""
Генерация live-подсказок во время звонка: короткий вариант ответа +
напоминание релевантного факта из более раннего разговора.

Дёргается после каждой фразы собеседника — тут, в отличие от саммари после
звонка, задержка уже важна, поэтому: короткий промпт, ограниченный хвост
транскрипта вместо всего текста целиком, и жёсткий лимит длины ответа модели.

Раньше решение "нужен ли веб-поиск" всегда было отдельным первым запросом к
Ollama, и только потом — второй запрос за самим ответом. То есть КАЖДАЯ
подсказка ждала два похода к модели подряд, даже когда поиск вообще не
нужен (а это большинство случаев) — лишние секунды задержки просто так.

Теперь один запрос: модель либо сразу отвечает в формате ОТВЕТ/КОНТЕКСТ,
либо, если ей для качественного ответа реально нужны свежие данные, вместо
ответа выводит "ПОИСК: <запрос>" — и только тогда делается вторая, уже
неизбежная итерация (поиск + финальный ответ с его результатами). Обычный
разговор без нужды в поиске теперь укладывается в один запрос вместо двух.
"""

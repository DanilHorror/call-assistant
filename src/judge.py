@dataclass
class KnownTag:
    """
    Один уже существующий тег из этого разговора. Судье нужен не абстрактный
    идентификатор тега сам по себе, а краткое описание того, О ЧЁМ он — иначе
    сопоставление свелось бы к случайному совпадению строк, а не к пониманию
    смысла (см. правило 1 в _JUDGE_SYSTEM_PROMPT).
    """
    tag: str
    summary: str  # например: "пример кода на Python — вычисление чисел Фибоначчи рекурсией"
    turns_ago: int  # сколько реплик назад тема встречалась последний раз — для recency (правило 2)


@dataclass
class JudgeVerdict:
    verdict: str  # "новый" | "продолжение" | "мусор"
    tags: list[str] = field(default_factory=list)
    continues_tags: list[str] = field(default_factory=list)
    ambiguous: bool = False
    ambiguous_options: list[str] = field(default_factory=list)
    raw: str = ""  # сырой ответ модели целиком — для отладки и логов теста
    parse_error: str | None = None  # заполняется, если JSON не разобрался (см. _parse_judge_output)

    @property
    def is_garbage(self) -> bool:
        return self.verdict == "мусор"

    @property
    def is_continuation(self) -> bool:
        return self.verdict == "продолжение"


def _format_known_tags(known_tags: list[KnownTag]) -> str:
    if not known_tags:
        return "Известные теги: (нет)\n"
    lines = ["Известные теги:"]
    for kt in known_tags:
        lines.append(f"- {kt.tag} ({kt.turns_ago} реплик(и) назад): {kt.summary}")
    return "\n".join(lines) + "\n"


def _build_judge_user_message(
    current_line: str,
    history: str,
    known_tags: list[KnownTag],
) -> str:
    parts = [_format_known_tags(known_tags)]
    if history:
        parts.append(f"История разговора:\n{history}\n")
    else:
        parts.append("История разговора: (нет)\n")
    parts.append(f"ТЕКУЩАЯ ФРАЗА:\n{current_line}\n")
    return "\n".join(parts)



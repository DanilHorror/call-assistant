# строка компактного JSON. 250 — с запасом хватает даже на ambiguous_options
# из нескольких формулировок (было 400 при открытом рассуждении, 300 до
# него — см. комментарий у _JUDGE_SYSTEM_PROMPT). Уменьшение важно само по
# себе: num_predict тоже входит в num_ctx=2048 вместе с промтом (см.
# проектный документ про переполнение) — каждый лишний зарезервированный
# токен вывода это токен, отнятый у промта.
_JUDGE_NUM_PREDICT = 250


def _call_ollama_judge(
    user_message: str,
    model: str,
    host: str,
    timeout: float,
    session: requests.Session,
    num_ctx: int | None = None,
) -> str:
    response = session.post(
        f"{host.rstrip('/')}/api/chat",
        json={
            "model": model,
            "messages": [
                {"role": "system", "content": _JUDGE_SYSTEM_PROMPT},
                {"role": "user", "content": user_message},
            ],
            "stream": False,
            "think": False,
            # БЕЗ "format": "json" — намеренно: этот режим заставляет Ollama
            # генерировать валидный JSON уже ПЕРВЫМ токеном, а значит не даёт
            # модели ни слова "подумать" перед решением. На живом тесте это
            # оказалось критично именно для пограничных решений (см. комментарий
            # у _JUDGE_SYSTEM_PROMPT) — с "format": "json" модель дважды подряд
            # неверно классифицировала явно разные темы как "не ambiguous",
            # хотя правило было прописано текстом. Разрешили короткое
            # рассуждение перед JSON вместо этого — синтаксическая валидность
            # JSON здесь уже не гарантирована схемой Ollama, поэтому парсинг
            # (_parse_judge_output) сначала пробует распарсить всё как есть, а
            # при неудаче вытаскивает JSON-блок из середины текста через regex.
            "options": {
                "num_predict": _JUDGE_NUM_PREDICT,
                "temperature": 0.0,  # см. обоснование в live_hints.py._call_ollama — жадное декодирование
                "repeat_penalty": 1.3,
                **({"num_ctx": num_ctx} if num_ctx is not None else {}),
            },
            "keep_alive": "30m",
        },
        timeout=timeout,
    )
    response.raise_for_status()
    return response.json()["message"]["content"]


# Round 9 (после того как JUDGE_NUM_CTX снял переполнение контекста):
# batch_test_judge.py вскрыл РЕАЛЬНЫЙ баг парсера, который раньше маскировался
# обрезкой контекста — на кейсе continuation_pronoun_reference модель (раз
# теперь есть запас num_predict/num_ctx) после первого ВЕРНОГО json-объекта
# иногда дописывает ВТОРОЙ, отформатированный (в ```json блоке, с переносами
# строк) дубликат того же ответа. Старый regex r"\{.*\}" ЖАДНЫЙ — с DOTALL он
# захватывает от ПЕРВОЙ "{" до ПОСЛЕДНЕЙ "}" во всём тексте, то есть склеивает
# оба JSON-объекта в один синтаксически невалидный кусок ("Extra data").
# Простой r"\{.*?\}" (не жадный) тут работал бы, ПОКА в схеме нет вложенных
# объектов (сейчас нет — только массивы строк), но это хрупкое совпадение,
# а не гарантия на будущее. Вместо этого — правильный разбор со счётчиком
# вложенности скобок, учитывающий строковые литералы (чтобы "}" внутри
# значения строки не сбивал подсчёт): находит первую "{" и возвращает ПЕРВЫЙ
# синтаксически завершённый JSON-объект, что бы модель ни дописала после него.
def _extract_json_block(text: str) -> str | None:
    start = text.find("{")
    if start == -1:
        return None
    depth = 0
    in_string = False
    escape = False
    for i in range(start, len(text)):
        ch = text[i]
        if in_string:
            if escape:
                escape = False
            elif ch == "\\":
                escape = True
            elif ch == '"':
                in_string = False
            continue
        if ch == '"':
            in_string = True
        elif ch == "{":
            depth += 1
        elif ch == "}":
            depth -= 1
            if depth == 0:
                return text[start : i + 1]
    return None

# Реальный случай (live-звонок через GigaChat-путь, где судья всё равно
# работает через Ollama): модель вернула синтаксически ВАЛИДНЫЙ JSON, но со
# значением verdict="завершение" — придуманной, не предусмотренной схемой
# категорией (видимо, пыталась выразить "тема исчерпана", для чего в схеме
# просто нет слота). is_garbage/is_continuation по строковому сравнению этого
# бы не поймали — "завершение" тихо прошло бы как "не мусор, не продолжение,
# просто что-то" дальше по коду, известные теги обновились бы ошибочно (см.
# main.py/_update_known_tags). Поэтому валидируем verdict СТРОГО по трём
# разрешённым значениям — что угодно ещё считаем таким же промахом, как
# несложившийся JSON.
_VALID_VERDICTS = {"новый", "продолжение", "мусор"}


def _parse_judge_output(raw: str) -> JudgeVerdict:
    """
    Модель теперь ВСЕГДА пишет короткое рассуждение перед JSON (см. системный
    промт) — то есть в сыром тексте JSON гарантированно не единственное, что
    там есть. Прямой json.loads() почти всегда упадёт на первой попытке (текст
    рассуждения впереди — это не валидный JSON сам по себе), поэтому основной
    путь — вытащить JSON-блок через _extract_json_block (счётчик вложенности
    скобок с первой "{", а не жадный regex — см. комментарий у функции, round 9:
    жадный вариант ломался, когда модель дописывала ВТОРОЙ дублирующий JSON
    после первого верного). Прямая попытка перед этим остаётся на случай, если
    модель когда-нибудь ответит совсем без рассуждения — тогда json.loads()
    сработает с первого раза без обращения к _extract_json_block.
    """
    text = raw.strip()
    for candidate in (text, _extract_json_block(text)):
        if candidate is None:
            continue
        try:
            data = json.loads(candidate)
        except json.JSONDecodeError:
            continue
        verdict = str(data.get("verdict", "")).strip().lower()
        if verdict not in _VALID_VERDICTS:
            return JudgeVerdict(
                verdict="",
                raw=raw,
                parse_error=f"неизвестный verdict от модели: {verdict!r} (допустимо: {sorted(_VALID_VERDICTS)})",
            )
        return JudgeVerdict(
            verdict=verdict,
            tags=[str(t).strip() for t in data.get("tags", []) if str(t).strip()],
            continues_tags=[str(t).strip() for t in data.get("continues_tags", []) if str(t).strip()],
            ambiguous=bool(data.get("ambiguous", False)),
            ambiguous_options=[str(o).strip() for o in data.get("ambiguous_options", []) if str(o).strip()],
            raw=raw,
        )
    # Ни прямой парсинг, ни извлечение JSON-блока не сработали — возвращаем
    # явно помеченный "промах", а не тихо притворяемся, что это "мусор". Вызывающий
    # код (main.py, когда судья будет подключён) должен на parse_error сам
    # решить fallback — например, пропустить фразу через старый regex-гейт,
    # а не терять её молча.
    return JudgeVerdict(verdict="", raw=raw, parse_error="не удалось разобрать JSON из ответа модели")



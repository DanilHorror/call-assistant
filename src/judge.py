# (не вероятностная), поэтому измеренный 46%-й провал закрывается полностью,
# а не частично.
_NEGATION_STARTS = {
    "нет", "неа", "не", "нее", "неее", "наоборот", "неверно", "необязательно",
}
_OWN_QUESTION_CONFIRMATION_MAX_WORDS = 6


def _is_own_question_confirmation(current_line: str, history: str) -> bool:
    """
    True, если current_line структурно похожа на подтверждение/ответ на
    СВОЙ ЖЕ уточняющий вопрос, заданный ПОСЛЕДНЕЙ ЧЕЛОВЕЧЕСКОЙ репликой в
    history (round 10, рычаг 1 — полное обоснование в комментарии выше).
    Намеренно НЕ смотрит на смысл фразы, только на структуру:

      1) последняя строка в history, начинающаяся с "Я: " или
         "Собеседник: " (см. round 10b ниже про то, почему именно так, а не
         "последняя непустая строка") — реплика "Я", заканчивающаяся на "?"
         (тот самый уточняющий вопрос);
      2) current_line — реплика "Собеседник" (не "Я" — иначе это была бы
         реплика самого спросившего, а не ответ на его вопрос);
      3) current_line короткая (<= _OWN_QUESTION_CONFIRMATION_MAX_WORDS слов)
         — длинный ответ может нести самостоятельную новую деталь, такое
         по-прежнему должно идти обычным путём через судью, не через этот
         короткий путь;
      4) current_line не начинается с отрицания (_NEGATION_STARTS) и сама не
         похожа на встречный вопрос (не содержит "?") — иначе это может быть
         "нет, я про другое" или новый вопрос, а не подтверждение.

    Round 10b (после первого прогона стресс-теста С рычагом 1 —
    data/stress_test_300_results_round10.csv): исходная версия смотрела на
    ПОСЛЕДНЮЮ НЕПУСТУЮ строку history — и не сработала на 5/24 кейсов
    clarify_confirmation, хотя структурно они ничем не отличались от
    сработавших. Причина, найдена реконструкцией реального окна истории по
    CSV: между "Я: ...?" и ответом собеседника в history оказывается
    реплика "Ассистент: ..." (тестовый скрипт, в отличие от process_loop() в
    main.py, генерирует подсказку НА ЛЮБУЮ реплику без исключения для "Я" —
    в реальном live-пути с HINTS_ON_MIC=false по умолчанию такой реплики
    "Ассистент" между ними не будет, но эвристика должна быть надёжной и
    при HINTS_ON_MIC=true тоже, раз в конфиге есть такая настройка). Кроме
    того, часть сгенерированных ответов сама содержит перенос строки
    (например хвост вида "...\nКОНТЕКСТ: <текст>") — после разбиения history
    по строкам это выглядит как ещё одна "строка" без метки говорящего
    вообще. Простое "пропускать только строки, начинающиеся с 'Ассистент: '"
    эту вторую проблему не решает. Правильный, надёжный признак — не
    "последняя строка" и не "последняя не-Ассистент строка", а "последняя
    строка, начинающаяся именно с 'Я: ' или 'Собеседник: '" — то есть ищем
    последнюю по-настоящему ЧЕЛОВЕЧЕСКУЮ реплику, игнорируя и сами ответы
    ассистента, и любые перенесённые без метки говорящего продолжения их
    текста. Проверено на реконструированной истории всех 299 реплик round
    10b: 24/24 clarify_confirmation теперь распознаются, 0 ложных
    срабатываний на остальных 275 репликах (см. проектный документ).
    """
    if not current_line.startswith("Собеседник: ") or "?" in current_line:
        return False
    last_human_line = ""
    for raw_line in reversed(history.splitlines()):
        stripped = raw_line.strip()
        if stripped.startswith("Я: ") or stripped.startswith("Собеседник: "):
            last_human_line = stripped
            break
        # Всё остальное — пустые строки, строки "Ассистент: ...", и любые
        # перенесённые без метки говорящего продолжения многострочного
        # текста (см. round 10b выше) — не человеческая реплика, идём
        # глубже в историю, а не считаем это концом поиска.
    if not (last_human_line.startswith("Я: ") and last_human_line.endswith("?")):
        return False
    phrase = current_line[len("Собеседник: ") :].strip()
    words = re.findall(r"[а-яА-ЯёЁa-zA-Z]+", phrase.lower())
    if not words or len(words) > _OWN_QUESTION_CONFIRMATION_MAX_WORDS:
        return False
    return words[0] not in _NEGATION_STARTS


def classify_utterance(
    current_line: str,
    history: str,
    known_tags: list[KnownTag],
    model: str,
    host: str,
    timeout: float,
    session: requests.Session,
    num_ctx: int | None = None,
) -> JudgeVerdict:
    """
    Точка входа для остального кода (пока — только batch_test_judge.py; после
    валидации промта — main.py/process_loop(), ПЕРЕД отправкой в GigaChat).

    current_line — строка вида "Собеседник: <текст>" / "Я: <текст>" (тот же
    формат, что _split_current_line отдаёт в live_hints.py).
    history — тот же текст, что уходит в generate_hint() как "История
    разговора" (recent_text(HINTS_CONTEXT_LINES) в текущем коде main.py).
    known_tags — теги, накопленные за разговор (см. KnownTag) — в реальном
    live-пути будут копиться по ходу звонка; здесь передаются как параметр,
    чтобы модуль не зависел от того, ГДЕ они хранятся.
    """
    # Round 10, рычаг 1 — см. комментарий у _is_own_question_confirmation.
    # Структурная проверка ПЕРЕД обращением к модели вообще: если условие
    # выполняется, возвращаем "продолжение" сразу, без похода в Ollama — это
    # и быстрее, и не зависит от того, встречала ли модель именно такую
    # формулировку подтверждения в промте.
    if known_tags and _is_own_question_confirmation(current_line, history):
        target_tag = min(known_tags, key=lambda kt: kt.turns_ago).tag
        return JudgeVerdict(
            verdict="продолжение",
            tags=[target_tag],
            continues_tags=[target_tag],
            ambiguous=False,
            ambiguous_options=[],
            raw="<рычаг 1: структурная проверка подтверждения своего вопроса, без обращения к модели>",
        )

    user_message = _build_judge_user_message(current_line, history, known_tags)
    raw = _call_ollama_judge(user_message, model, host, timeout, session, num_ctx=num_ctx)
    return _parse_judge_output(raw)
